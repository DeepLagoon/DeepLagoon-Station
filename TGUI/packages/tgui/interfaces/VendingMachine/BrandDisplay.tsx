function brandName(title: string) {
  const name = title.replace(/(^|[\s«"'(])(?:торговый\s+автомат|vending\s+machine)(?=$|[\s»"')—–:\-])/gi, '$1')
    .replace(/^[\s—–\-:]+|[\s—–\-:]+$/g, '').replace(/\s+/g, ' ').trim();
  const quotes: Record<string, string> = { '«': '»', '"': '"', "'": "'", '„': '“', '“': '”' };
  return name.length > 1 && quotes[name[0]] === name[name.length - 1] ? name.slice(1, -1).trim() : name;
}

export const BrandDisplay = memo(({ title, powered }: { title: string; powered: boolean }) => {
  const element = useRef<HTMLHeadingElement>(null);
  const [size, setSize] = useState({ width: 640, height: 100 });
  const pattern = 'vending-bulbs-' + useId().replace(/[^a-z0-9_-]/gi, '');
  const name = brandName(title);
  useEffect(() => {
    const root = element.current;
    if (!root) return;
    const measure = () => setSize(previous => previous.width === root.clientWidth && previous.height === root.clientHeight
      ? previous : { width: root.clientWidth, height: root.clientHeight });
    const observer = new ResizeObserver(measure); observer.observe(root); measure();
    return () => observer.disconnect();
  }, []);
  const bulbs = useMemo(() => {
    const text = [...name.toUpperCase()];
    const width = Math.max(1, size.width), height = Math.max(1, size.height);
    const unit = Math.min(height / 9, width / Math.max(7, text.length * 6 + 1));
    const gap = text.length > 1 ? (width - unit * (5 * text.length + 2)) / (text.length - 1) : 0;
    const start = text.length === 1 ? (width - 5 * unit) / 2 : unit;
    const top = (height - 7 * unit) / 2;
    const points: { x: number; y: number }[] = [];
    text.forEach((character, index) => (GLYPHS[character] ?? GLYPHS['?']).forEach((row, y) => [...row].forEach((pixel, x) => {
      if (pixel === '1') points.push({ x: start + index * (5 * unit + gap) + (x + .5) * unit, y: top + (y + .5) * unit });
    })));
    return { width, height, unit, points };
  }, [name, size]);
  return <h1 ref={element} className={`VendingMachine__brand-title${powered ? '' : ' is-off'}`} aria-label={name}>
    <svg viewBox={`0 0 ${bulbs.width} ${bulbs.height}`} width="100%" height="100%" aria-hidden="true">
      <defs><pattern id={pattern} width={bulbs.unit} height={bulbs.unit} patternUnits="userSpaceOnUse"><circle cx={bulbs.unit / 2} cy={bulbs.unit / 2} r={bulbs.unit * .25} fill="#16170f" /></pattern></defs>
      <rect width="100%" height="100%" fill={`url(#${pattern})`} />
      <g className="VendingMachine__brand-bulbs">{bulbs.points.map((point, index) => <circle key={index} cx={point.x} cy={point.y} r={bulbs.unit * .28} />)}</g>
    </svg>
  </h1>;
});
