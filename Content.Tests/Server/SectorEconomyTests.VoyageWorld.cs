    private static readonly string[] VoyageRoutes = [VoyageWorld.Key("colossus", "helios"), VoyageWorld.Key("helios", "sector-7-0")];
    private async Task<VoyageWorld> ReadWorld(bool allowNew = true, long now = 1000)
    { await using var db = new SqliteServerDbContext(_options); return await EconomyOperations.ReadVoyageWorld(db, allowNew, VoyageRoutes, now); }
    private async Task SaveWorld(VoyageWorld world)
    {
        await using var db = new SqliteServerDbContext(_options);
        (await db.LagoonEconomyRecords.FindAsync("voyage:world:v2"))!.Data = JsonSerializer.Serialize(world); await db.SaveChangesAsync();
    }
    private async Task CommitJob(VoyageJob job)
    { await using var db = new SqliteServerDbContext(_options); await EconomyOperations.CommitVoyage(db, job, null); }
    [Test]
    public async Task VoyageMarketUsesStoredRandomTierPricesAndPurchaseIsAtomicAndIdempotent()
    {
        var world = await ReadWorld(); var profile = await ProfileId(_user);
        Assert.That(world.Offers, Has.Count.EqualTo(12));
        foreach (var type in new[] { "cargo", "survey", "express", "mercenary" })
        {
            Assert.That(world.Offers.Any(o => o.Type == type && o.Level == 1), Is.True);
            var previous = 0;
            for (var level = 1; level <= 5; level++)
            { var price = VoyageWorld.HirePrice(type, level); Assert.That(price, Is.GreaterThan(previous)); previous = price; }
        }
        // Preserve an actual higher-tier quote as if generated by the market.
        var offer = VoyageWorld.NewOffer("mercenary", 3); world.Offers[0] = offer; await SaveWorld(world);
        var operation = Guid.NewGuid();
        await using (var db = new SqliteServerDbContext(_options))
        {
            var hired = await EconomyOperations.HireVoyageMarketCrew(db, _user, profile, 0, offer.Id, operation);
            Assert.That(hired.Level, Is.EqualTo(3)); Assert.That(hired.Experience, Is.EqualTo(180));
            Assert.That(hired.HirePrice, Is.EqualTo(offer.Cost));
        }
        await using (var db = new SqliteServerDbContext(_options))
        {
            await EconomyOperations.HireVoyageMarketCrew(db, _user, profile, 0, offer.Id, operation);
            Assert.That((await EconomyOperations.ReadVoyages(db, _user, profile)).Bank, Is.EqualTo(800000 - offer.Cost));
        }
        await using (var db = new SqliteServerDbContext(_options))
            Assert.ThrowsAsync<InvalidOperationException>(async () => await EconomyOperations.HireVoyageMarketCrew(db, _user, profile, 0, offer.Id, Guid.NewGuid()));
        Assert.That((await ReadWorld(false)).Offers.Any(o => o.Id == offer.Id), Is.False);
    }
    [TestCase(0d, 0)]
    [TestCase(.5d, 1)]
    [TestCase(.99d, 2)]
    public async Task LostMercenariesMayFailSuppressOrEradicatePiracyIndependentlyOfSurvival(double combatRoll, int expected)
    {
        var world = await ReadWorld(); var crew = await HireCrew();
        var key = VoyageRoutes[0]; world.Routes[key].Last = .8; world.Routes[key].At = 61000; await SaveWorld(world);
        var job = Job(crew) with { Kind = 3, Reward = 0, Cycle = world.Cycle, OutRoll = 0, BackRoll = .99, CombatRoll = combatRoll };
        await CommitJob(job);
        var outcome = await AdvanceJob(job.Id, job.Arrive);
        Assert.That(outcome.Failed, Is.True); Assert.That(outcome.Paid, Is.True); Assert.That(outcome.Combat, Is.EqualTo(expected));
        var after = await ReadWorld(false, job.Arrive);
        Assert.That(after.Routes[key].Value(job.Arrive), Is.EqualTo(expected == 0 ? .8 : expected == 1 ? .28 : 0).Within(.00001));
        var retry = await AdvanceJob(job.Id, job.Return); Assert.That(retry.Combat, Is.EqualTo(outcome.Combat)); Assert.That(retry.Failed, Is.True);
        await using var db = new SqliteServerDbContext(_options);
        var state = await EconomyOperations.ReadVoyages(db, _user, crew.Profile);
        Assert.That(state.Crews, Is.Empty); Assert.That(state.Bank, Is.EqualTo(794000));
        var lost = JsonSerializer.Deserialize<VoyageCrewRecord>((await db.LagoonEconomyRecords.FindAsync("voyage:crew:" + crew.Id.ToString("N")))!.Data)!;
        Assert.That(lost.Lost, Is.True); Assert.That(lost.Experience, Is.Zero);
    }
    [Test]
    public async Task SurvivingCrewLevelsOnceOnlyAfterReturnAndImportCargoCannotBeClaimedTwice()
    {
        var world = await ReadWorld(); var crew = await HireCrew();
        await using (var db = new SqliteServerDbContext(_options))
        {
            var row = (await db.LagoonEconomyRecords.FindAsync("voyage:crew:" + crew.Id.ToString("N")))!;
            row.Data = JsonSerializer.Serialize(crew with { Experience = 55 }); await db.SaveChangesAsync();
        }
        var job = Job(crew) with { Kind = 2, Reward = 0, Cycle = world.Cycle, Product = "SheetSteel", Quantity = 2, PurchaseCost = 20000, OutRoll = .999, BackRoll = .999 };
        await CommitJob(job); await CommitJob(job);
        await AdvanceJob(job.Id, job.Arrive);
        await using (var db = new SqliteServerDbContext(_options))
        {
            var state = await EconomyOperations.ReadVoyages(db, _user, crew.Profile);
            Assert.That(state.Bank, Is.EqualTo(774000)); Assert.That(state.Parcels, Is.Empty); Assert.That(state.Crews.Single().Experience, Is.EqualTo(55));
        }
        var returned = await AdvanceJob(job.Id, job.Return); await AdvanceJob(job.Id, job.Return + 1);
        Assert.That(returned.ExperienceAwarded, Is.True);
        var lease = Guid.NewGuid();
        await using (var db = new SqliteServerDbContext(_options))
        {
            var state = await EconomyOperations.ReadVoyages(db, _user, crew.Profile);
            Assert.That(state.Crews.Single().Level, Is.EqualTo(2)); Assert.That(state.Crews.Single().Experience, Is.EqualTo(64));
            Assert.That(state.Parcels.Single().Id, Is.EqualTo(job.Id));
            await EconomyOperations.IssueVoyageCargo(db, _user, crew.Profile, job.Id, lease, null);
        }
        await using (var db = new SqliteServerDbContext(_options))
        {
            await EconomyOperations.IssueVoyageCargo(db, _user, crew.Profile, job.Id, lease, null);
            Assert.That((await EconomyOperations.ReadVoyages(db, _user, crew.Profile)).Parcels, Is.Empty);
        }
        await using (var db = new SqliteServerDbContext(_options))
            Assert.ThrowsAsync<InvalidOperationException>(async () => await EconomyOperations.IssueVoyageCargo(db, _user, crew.Profile, job.Id, Guid.NewGuid(), null));
    }
