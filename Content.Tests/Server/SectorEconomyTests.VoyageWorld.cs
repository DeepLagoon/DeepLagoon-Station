    [Test]
    public async Task WorldSurvivesCrashButNormalClosureResetsMapWithoutDeletingCrewsOrPaidCargo()
    {
        var world = await ReadWorld(); world.Known.Add("sector-7-0");
        world.Research["echo"] = new SectorResearchProgress { Completed = [0, 2] }; await SaveWorld(world);
        var crew = await HireCrew();
        var job = Job(crew) with { Kind = 2, Reward = 0, Cycle = world.Cycle, Product = "SheetSteel", Quantity = 1, PurchaseCost = 5000, OutRoll = .999, BackRoll = .999 };
        await CommitJob(job); await AdvanceJob(job.Id, job.Return);
        var scout = Job(crew) with { Id = Guid.NewGuid(), Survey = true, Kind = 1, Cycle = world.Cycle, Reward = 0, Destination = "sector-0-0", OutRoll = .999, BackRoll = .999 };
        await CommitJob(scout);
        var restart = await ReadWorld(false); Assert.That(restart.Cycle, Is.EqualTo(world.Cycle)); Assert.That(restart.Seed, Is.EqualTo(world.Seed)); Assert.That(restart.Known, Does.Contain("sector-7-0"));
        Assert.That(restart.Research["echo"].Completed, Is.EquivalentTo(new[] { 0, 2 }));
        await using (var db = new SqliteServerDbContext(_options)) await EconomyOperations.CloseVoyageWorld(db, world.Cycle);
        Assert.That((await ReadWorld(false)).Known, Is.Empty);
        var next = await ReadWorld(); Assert.That(next.Cycle, Is.Not.EqualTo(world.Cycle)); Assert.That(next.Known, Is.Empty);
        Assert.That(next.Research, Is.Empty);
        await AdvanceJob(scout.Id, scout.Return);
        Assert.That((await ReadWorld(false)).Known, Is.Empty, "An old voyage must not reveal routes in the new round.");
        await using (var db = new SqliteServerDbContext(_options))
        { var state = await EconomyOperations.ReadVoyages(db, _user, crew.Profile); Assert.That(state.Crews, Has.Length.EqualTo(1)); Assert.That(state.Parcels, Has.Length.EqualTo(1)); Assert.That(state.Bank, Is.EqualTo(789000)); }
    }
    [Test]
    public void PiracyHasDistanceRiskTemporaryEradicationRegrowthAndIncidentsOnAnyLane()
    {
        var world = new VoyageWorld(); world.EnsureRoutes(VoyageRoutes, 1000);
        Assert.That(world.Routes[VoyageRoutes[1]].Value(1000), Is.GreaterThan(world.Routes[VoyageRoutes[0]].Value(1000)));
        var path = new[] { "colossus", "helios" };
        Assert.That(world.Risk(path, 1000, 5, false), Is.LessThan(world.Risk(path, 1000, 1, false)));
        world.ApplyCombat(path, 2, 1000); Assert.That(world.Risk(path, 1001, 1, false), Is.Zero);
        var quiet = world.Routes[VoyageRoutes[0]].QuietUntil;
        Assert.That(world.Routes[VoyageRoutes[0]].Value(quiet + 1800000), Is.EqualTo(.0125).Within(.00001));
        // A fresh attack can appear on a fully cleared route without waiting for passive recovery.
        world.Routes.Remove(VoyageRoutes[1]); world.NextRaid = 1001; world.EnsureRoutes([], 1001);
        Assert.That(world.Routes[VoyageRoutes[0]].Value(1001), Is.GreaterThanOrEqualTo(.15));
    }
