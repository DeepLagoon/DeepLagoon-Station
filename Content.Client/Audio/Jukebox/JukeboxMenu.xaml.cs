using System.Threading.Tasks;
using Content.Shared.Audio.Jukebox;
using Robust.Client.Audio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio.Components;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client.Audio.Jukebox;

[GenerateTypedNameReferences]
public sealed partial class JukeboxMenu : FancyWindow
{
    [Dependency] private IEntityManager _entManager = default!;
    private AudioSystem _audioSystem;

    /// <summary>
    /// Are we currently 'playing' or paused for the play / pause button.
    /// </summary>
    private bool _playState;

    /// <summary>
    /// True if playing, false if paused.
    /// </summary>
    public event Action<bool>? OnPlayPressed;
    public event Action? OnStopPressed;
    public event Action<ProtoId<JukeboxPrototype>>? OnSongSelected;
    public event Action<float>? SetTime;
    public event Action<float>? SetGain; // Exodus Volume slider to jukebox
    private EntityUid? _audio;

    private float _lockTimer;
    private float _selectedLength;
    private Task<JukeboxCatalog>? _catalogIndex;
    private Task<(JukeboxCatalog Index, JukeboxCatalog.Page Page)>? _catalogPageTask;
    private int _catalogPage;
    private bool _catalogDirty;
    private float _searchWait;

    public JukeboxMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _audioSystem = _entManager.System<AudioSystem>();

        MusicList.OnItemSelected += args =>
        {
            var entry = MusicList[args.ItemIndex];

            if (entry.Metadata is not string juke)
                return;

            OnSongSelected?.Invoke(juke);
        };

        PlayButton.OnPressed += args =>
        {
            OnPlayPressed?.Invoke(!_playState);
        };

        StopButton.OnPressed += args =>
        {
            OnStopPressed?.Invoke();
        };
        PlaybackSlider.OnReleased += PlaybackSliderKeyUp;

        VolumeSlider.OnReleased += VolumeSliderOnReleased; // Exodus Volume slider to jukebox

        SetPlayPauseButton(_audioSystem.IsPlaying(_audio), force: true);
        CatalogSearch.OnTextChanged += _ => { _catalogPage = 0; _catalogDirty = true; _searchWait = .15f; };
        PreviousPage.OnPressed += _ => { _catalogPage--; _catalogDirty = true; };
        NextPage.OnPressed += _ => { _catalogPage++; _catalogDirty = true; };
    }

    public JukeboxMenu(AudioSystem audioSystem)
    {
        _audioSystem = audioSystem;
    }

    public void SetAudioStream(EntityUid? audio)
    {
        _audio = audio;
    }

    private void PlaybackSliderKeyUp(Slider args)
    {
        SetTime?.Invoke(PlaybackSlider.Value);
        _lockTimer = 0.5f;
    }

    /// <summary>
    /// Re-populates the list of jukebox prototypes available.
    /// </summary>
    public void Populate(Task<JukeboxCatalog> catalog)
    {
        _catalogIndex = catalog;
        _catalogDirty = true;
    }

    private void UpdateCatalog(float seconds)
    {
        _searchWait -= seconds;
        if (_catalogPageTask is { IsCompleted: true } finished)
        {
            _catalogPageTask = null;
            if (!_catalogDirty)
            {
                var (index, page) = finished.GetAwaiter().GetResult();
                _catalogPage = page.Index;
                MusicList.Clear();
                foreach (var row in page.Rows)
                    MusicList.AddItem(index.Name(row.Track), metadata: row.Track);
                CatalogPage.Text = $"{page.Index + 1}/{Math.Max(1, (page.Total + JukeboxCatalog.PageSize - 1) / JukeboxCatalog.PageSize)}";
                PreviousPage.Disabled = page.Index == 0;
                NextPage.Disabled = (page.Index + 1) * JukeboxCatalog.PageSize >= page.Total;
            }
        }
        if (_catalogPageTask != null || !_catalogDirty || _searchWait > 0 || _catalogIndex == null) return;
        _catalogDirty = false;
        PreviousPage.Disabled = NextPage.Disabled = true;
        var catalog = _catalogIndex;
        var query = CatalogSearch.Text;
        var requestedPage = _catalogPage;
        _catalogPageTask = Task.Run(async () =>
        {
            var index = await catalog;
            return (index, index.Browse(null, query, requestedPage));
        });
    }

    public void SetPlayPauseButton(bool playing, bool force = false)
    {
        if (_playState == playing && !force)
            return;

        _playState = playing;

        if (playing)
        {
            PlayButton.Text = Loc.GetString("jukebox-menu-buttonpause");
            return;
        }

        PlayButton.Text = Loc.GetString("jukebox-menu-buttonplay");
    }

    public void SetSelectedSong(string name, float length)
    {
        _selectedLength = length;
        SetSelectedSongText(name);
        PlaybackSlider.MaxValue = length;
        PlaybackSlider.SetValueWithoutEvent(0);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCatalog(args.DeltaSeconds);

        if (_lockTimer > 0f)
        {
            _lockTimer -= args.DeltaSeconds;
        }

        PlaybackSlider.Disabled = _lockTimer > 0f;

        if (_entManager.TryGetComponent(_audio, out AudioComponent? audio))
        {
            DurationLabel.Text = $@"{TimeSpan.FromSeconds(audio.PlaybackPosition):mm\:ss} / {TimeSpan.FromSeconds(_selectedLength):mm\:ss}";
        }
        else
        {
            DurationLabel.Text = $"00:00 / 00:00";
        }

        if (PlaybackSlider.Grabbed)
            return;

        if (audio != null || _entManager.TryGetComponent(_audio, out audio))
        {
            PlaybackSlider.SetValueWithoutEvent(audio.PlaybackPosition);
        }
        else
        {
            PlaybackSlider.SetValueWithoutEvent(0f);
        }

        SetPlayPauseButton(_audioSystem.IsPlaying(_audio, audio));
    }

    public void SetSelectedSongText(string? text)
    {
        if (!string.IsNullOrEmpty(text))
        {
            SongName.Text = text;
        }
        else
        {
            SongName.Text = "---";
        }
    }

    // Exodus-begin Volume slider to jukebox
    private void VolumeSliderOnReleased(Slider args)
    {
        SetGain?.Invoke(args.Value);
    }

    public void SetGainValue(float gain)
    {
        VolumeSlider.Value = Math.Clamp(gain, 0f, 1f);
    }
    // Exodus-end
}
