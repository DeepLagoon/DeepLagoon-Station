    }

    protected void DrawData(DrawingHandleScreen handle, string text)
    {
        var coordsDimensions = handle.GetDimensions(Font, text, 1f);
        const float coordsMargins = 5f;

        handle.DrawString(Font,
            new Vector2(coordsMargins, PixelHeight) - new Vector2(0f, coordsDimensions.Y + coordsMargins),
            text,
            Color.FromSrgb(IFFComponent.SelfColor));
    }

    protected void DrawGreenZone(DrawingHandleScreen handle, Vector2 center, float radius, string name)
    {
        var viewport = (Vector2) PixelSize;
        var nearest = Vector2.Clamp(center, Vector2.Zero, viewport);
        if (Vector2.DistanceSquared(nearest, center) > radius * radius)
            return;

        handle.DrawCircle(center, radius, GreenZoneColor.WithAlpha(0.09f));
        handle.DrawCircle(center, radius, GreenZoneColor, filled: false);

        if (nearest != center && Vector2.DistanceSquared(MidPointVector, center) > radius * radius)
            return;

        var inset = new Vector2(8f) * UIScale;
        var labelSize = handle.GetDimensions(Font, name, UIScale);
        var label = nearest == center ? center + inset : inset;
        label = Vector2.Clamp(label, inset, Vector2.Max(inset, viewport - labelSize - inset));
        handle.DrawString(Font, label, name, UIScale, GreenZoneColor);
    }

    protected void DrawCircles(DrawingHandleScreen handle)
    {
        // Equatorial lines
        var gridLines = FitViewport ? Color.FromHex("#57818D") : Color.LightGray;

        // Each circle is this x distance of the last one.
        const float EquatorialMultiplier = 2f;

        var minDistance = MathF.Pow(EquatorialMultiplier, EquatorialMultiplier * 1.5f);
        var maxDistance = MathF.Pow(2f, EquatorialMultiplier * 6f);
        var cornerDistance = ViewportWorldHalfExtents.Length();

        var origin = MidPointVector; // Mono

        for (var radius = minDistance; radius <= maxDistance; radius *= EquatorialMultiplier)
        {
            if (radius > cornerDistance)
                continue;

            var color = FitViewport ? gridLines.WithAlpha(0.24f) : Color.ToSrgb(gridLines).WithAlpha(0.05f);
            var scaledRadius = MinimapScale * radius;
            var text = $"{radius:0}m";
            var textDimensions = handle.GetDimensions(Font, text, UIScale);

            if (FitViewport && scaledRadius > 1)
            {
                handle.DrawCircle(origin, scaledRadius - 0.55f, WarmFringe.WithAlpha(0.025f), false);
                handle.DrawCircle(origin, scaledRadius + 0.55f, CoolFringe.WithAlpha(0.03f), false);
            }
            handle.DrawCircle(origin, scaledRadius, color, false);
            handle.DrawString(Font, ScalePosition(new Vector2(0f, -radius)) - new Vector2(0f, textDimensions.Y), text, UIScale,
                FitViewport ? gridLines.WithAlpha(0.7f) : color);
        }

        const int gridLinesRadial = 8;

        for (var i = 0; i < gridLinesRadial; i++)
        {
            Angle angle = (Math.PI / gridLinesRadial) * i;
            // TODO: Handle distance properly.
            var aExtent = angle.ToVec() * (FitViewport ? ((Vector2) PixelSize).Length() / 2 : ScaledMinimapRadius * 1.42f);
            var lineColor = FitViewport ? gridLines.WithAlpha(0.16f) : Color.MediumSpringGreen.WithAlpha(0.02f);
            DrawRadarGuideLine(handle, origin - aExtent, origin + aExtent, lineColor);
        }
    }

    // Frontier Corvax: north line drawing
    protected void DrawNorthLine(DrawingHandleScreen handle, Angle angle)
    {
        var origin = MidPointVector;
        var aExtent = (angle - Math.Tau / 4).ToVec() * ScaledMinimapRadius * 1.42f;
        var lineColor = Color.Red.WithAlpha(0.1f);
        handle.DrawLine(origin, origin + aExtent, lineColor);
    }
