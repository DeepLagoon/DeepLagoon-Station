    protected void DrawGrid(DrawingHandleScreen handle, Matrix3x2 gridToView, Entity<MapGridComponent> grid,
        Color color, float alpha = 0.01f, bool drawFill = false)
    {
        if (!Matrix3x2.Invert(gridToView, out var viewToGrid))
            return;

        var visible = viewToGrid.TransformBox(new Box2(-1, -1, PixelWidth + 1, PixelHeight + 1));
        // Detection considers a wider area than the viewport. Skip even indexing offscreen grids.
        if (!grid.Comp.LocalAABB.Enlarged(ShuttleRadarGeometrySystem.OverviewStep * grid.Comp.TileSize).Intersects(visible))
            return;

        var tilePixels = new Vector2(gridToView.M11, gridToView.M12).Length() * grid.Comp.TileSize;
        var overview = tilePixels * ShuttleRadarGeometrySystem.OverviewStep <= 1f;
        var mesh = _radarMeshes.GetVisibleMesh(grid, visible, overview);
        var regionSize = ShuttleRadarGeometrySystem.RegionWorldSize(grid.Comp);

        CollectVisibleRadarGeometry(mesh, visible, regionSize, overview, drawFill);
        var original = handle.GetTransform();
        if (drawFill)
        {
            var backing = FitViewport ? Color.FromSrgb(RadarSurfaceColor) : BackingColor;
            color = Color.ToSrgb(Color.InterpolateBetween(backing, color, alpha)).WithAlpha(1f);
        }

        // Skip the extra color passes at distances where their subpixel offset is immaterial.
        if (!drawFill && FitViewport && !overview)
        {
            handle.SetTransform(gridToView * Matrix3x2.CreateTranslation(-0.45f, 0) * original);
            DrawGridMesh(handle, false, WarmFringe.WithAlpha(color.A * 0.1f));
            handle.SetTransform(gridToView * Matrix3x2.CreateTranslation(0.45f, 0) * original);
            DrawGridMesh(handle, false, CoolFringe.WithAlpha(color.A * 0.12f));
        }

        handle.SetTransform(gridToView * original);
        DrawGridMesh(handle, drawFill, color);
        handle.SetTransform(original);
        _visibleRadarRegions.Clear();
    }

    private void CollectVisibleRadarGeometry(ShuttleRadarGeometrySystem.GridMesh mesh,
        Box2 visible, int regionSize, bool overview, bool drawFill)
    {
        foreach (var (key, region) in mesh.Regions)
        {
            var geometry = overview ? region.Overview ?? region.Detail : region.Detail ?? region.Overview;
            if (geometry == null || !ShuttleRadarGeometrySystem.RegionBounds(key, regionSize).Intersects(visible))
                continue;

            _visibleRadarRegions.Add(drawFill ? geometry.Fill : geometry.Edges);
        }

        _visibleRadarMarkers.Clear();
        if (drawFill)
            return;

        for (var i = 0; i < mesh.Markers.Count; i += 2)
        {
            var first = mesh.Markers[i];
            var last = mesh.Markers[i + 1];
            var bounds = new Box2(Vector2.Min(first, last), Vector2.Max(first, last));
            if (!bounds.Intersects(visible))
                continue;

            _visibleRadarMarkers.Add(first);
            _visibleRadarMarkers.Add(last);
        }
    }

    private void DrawGridMesh(DrawingHandleScreen handle, bool drawFill, Color color)
    {
        var topology = drawFill ? DrawPrimitiveTopology.TriangleList : DrawPrimitiveTopology.LineList;
        var count = 0;
        foreach (var region in _visibleRadarRegions)
            AppendGridVertices(handle, topology, region, color, ref count);

        if (!drawFill)
            AppendGridVertices(handle, topology, System.Runtime.InteropServices.CollectionsMarshal.AsSpan(_visibleRadarMarkers), color, ref count);

        if (count != 0)
            handle.DrawPrimitives(topology, _radarVertices.AsSpan(0, count), color);
    }

    private void AppendGridVertices(DrawingHandleScreen handle, DrawPrimitiveTopology topology,
        ReadOnlySpan<Vector2> vertices, Color color, ref int count)
    {
        while (!vertices.IsEmpty)
        {
            var copied = Math.Min(vertices.Length, RadarVertexBatchSize - count);
            vertices[..copied].CopyTo(_radarVertices.AsSpan(count));
            vertices = vertices[copied..];
            count += copied;
            if (count != RadarVertexBatchSize)
                continue;

            handle.DrawPrimitives(topology, _radarVertices, color);
            count = 0;
        }
    }

    protected void DrawRadarPrimitives(DrawingHandleScreen handle, DrawPrimitiveTopology topology,
        ReadOnlySpan<Vector2> vertices, Color color)
    {
        // Sub-pixel chromatic aberration on radar outlines only. Reuse the same
        // cached geometry; hit testing, labels and aiming coordinates stay exact.
        if (FitViewport && vertices.Length > 0)
        {
            var transform = handle.GetTransform();
            handle.SetTransform(Matrix3x2.CreateTranslation(-0.45f, 0) * transform);
            DrawPrimitiveBatches(handle, topology, vertices, WarmFringe.WithAlpha(color.A * 0.1f));
            handle.SetTransform(Matrix3x2.CreateTranslation(0.45f, 0) * transform);
            DrawPrimitiveBatches(handle, topology, vertices, CoolFringe.WithAlpha(color.A * 0.12f));
            handle.SetTransform(transform);
        }
        DrawPrimitiveBatches(handle, topology, vertices, color);
    }

    // The engine's Vector2 overload allocates a converted vertex for every input on the stack.
    // Keep list batches small and aligned to complete primitives.
    internal const int RadarVertexBatchSize = 1536;

    protected internal static void DrawPrimitiveBatches(DrawingHandleScreen handle, DrawPrimitiveTopology topology,
        ReadOnlySpan<Vector2> vertices, Color color)
    {
        if (vertices.IsEmpty)
            return;

        if (topology is DrawPrimitiveTopology.LineList or DrawPrimitiveTopology.TriangleList)
        {
            for (var start = 0; start < vertices.Length; start += RadarVertexBatchSize)
                handle.DrawPrimitives(topology, vertices.Slice(start, Math.Min(RadarVertexBatchSize, vertices.Length - start)), color);

            return;
        }

        // The only connected primitive here is the fixed, four-vertex map cursor.
        handle.DrawPrimitives(topology, vertices, color);
    }

