using System;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Shared.Ghost;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;
using Content.Client.Lobby.UI;
using Robust.Client.Graphics;
using static Robust.Client.UserInterface.StylesheetHelpers;

namespace Content.Client.Voting.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class VotePopup : Control
    {
        [Dependency] private IGameTiming _gameTiming = default!;
        [Dependency] private IVoteManager _voteManager = default!;
        [Dependency] private IEntityNetworkManager _net = default!;

        private readonly VoteManager.ActiveVote _vote;
        private readonly Button[] _voteButtons;
        private readonly NetEntity? _targetEntity;
        private bool _lobbyStyle;

        public VotePopup(VoteManager.ActiveVote vote)
        {
            _vote = vote;
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);

            Stylesheet = IoCManager.Resolve<IStylesheetManager>().SheetSpace;

            if (_vote.TargetEntity != null && _vote.TargetEntity != 0)
            {
                _targetEntity = new NetEntity(_vote.TargetEntity.Value);
                FollowVoteTarget.Visible = true;
                FollowVoteTarget.OnPressed += _ => AttemptFollowVoteEntity();
            }

            Modulate = Color.White.WithAlpha(0.75f);
            _voteButtons = new Button[vote.Entries.Length];
            var group = new ButtonGroup();

            for (var i = 0; i < _voteButtons.Length; i++)
            {
                var button = new Button
                {
                    ToggleMode = true,
                    Group = group
                };
                _voteButtons[i] = button;
                VoteOptionsContainer.AddChild(button);
                var i1 = i;
                button.OnPressed += _ => _voteManager.SendCastVote(vote.Id, i1);
            }
        }

        public void ApplyLobbyStyle()
        {
            if (_lobbyStyle)
                return;
            _lobbyStyle = true;
            Modulate = Color.White;
            Frame.UseConsoleStyle = true;
            ScreenScanlines.Visible = true;
            Contents.Margin = new Thickness(LobbyConsoleTheme.ContentInset);
            Contents.SeparationOverride = 0;
            var font = LobbyConsoleTheme.GetFont();
            VoteCaller.FontOverride = LobbyConsoleTheme.GetFont(11);
            TimeLeftText.FontOverride = font;
            VoteCaller.FontColorOverride = LobbyConsoleTheme.Green.WithAlpha(0.62f);
            VoteCaller.OutlineThicknessOverride = 0;
            VoteCaller.ClipText = true;
            VoteCaller.Margin = new Thickness(0, 0, 0, 5);
            TimeLeftText.FontColorOverride = LobbyConsoleTheme.Green;
            VoteTitle.Margin = new Thickness(0, 0, 0, 12);
            VoteTitle.Stylesheet = new Stylesheet(new StyleRule[]
            {
                Element<RichTextLabel>().Prop("font", font).Prop(nameof(RichTextLabel.LineHeightScale), 1.6f)
                    .Prop("font-outline-thickness", 0f),
            });
            VoteOptionsContainer.Columns = 1;
            VoteOptionsContainer.VSeparationOverride = 3;
            foreach (var button in _voteButtons)
            {
                button.HorizontalExpand = true;
                button.Label.FontOverride = font;
                LobbyButtonArtwork.AttachUtility(button, nativeText: true);
            }
            FollowVoteTarget.Label.FontOverride = font;
            LobbyButtonArtwork.AttachUtility(FollowVoteTarget, nativeText: true);
            TimeLeftBar.UseLobbyStyle = true;
            TimeLeftBar.Margin = new Thickness(0);
            // The timer gets its own centered row. Its changing width can never
            // steal horizontal space from the full-width progress indicator.
            TimeLeftText.Orphan();
            var timer = new LobbyVoteTimer(TimeLeftText)
            {
                Name = "LobbyTimer",
            };
            ProgressRow.Orientation = BoxContainer.LayoutOrientation.Vertical;
            ProgressRow.Margin = new Thickness(4, 15, 4, 0);
            ProgressRow.SeparationOverride = 8;
            ProgressRow.AddChild(timer);
            timer.SetPositionFirst();
            var divider = new PanelContainer
            {
                MinHeight = 1,
                Margin = new Thickness(0, 0, 0, 2),
                PanelOverride = new StyleBoxFlat(LobbyConsoleTheme.Green.WithAlpha(0.17f)),
            };
            ProgressRow.AddChild(divider);
            divider.SetPositionFirst();
            UpdateData();
        }

        public void UpdateData()
        {
            VoteTitle.SetMessage(FormattedMessage.FromUnformatted(_vote.Title),
                defaultColor: _lobbyStyle ? LobbyConsoleTheme.Green : null);
            VoteCaller.Text = Loc.GetString("ui-vote-created", ("initiator", _vote.Initiator));
            if (_lobbyStyle)
                VoteCaller.ToolTip = VoteCaller.Text;

            for (var i = 0; i < _voteButtons.Length; i++)
            {
                var entry = _vote.Entries[i];
                if (_vote.DisplayVotes)
                {
                    // Mono
                    if (entry.RealVotes != entry.Votes)
                        _voteButtons[i].Text = Loc.GetString("ui-vote-button-weighted", ("text", entry.Text), ("votes", entry.Votes), ("realvotes", entry.RealVotes));
                    else
                        _voteButtons[i].Text = Loc.GetString("ui-vote-button", ("text", entry.Text), ("votes", entry.Votes));
                }
                else
                {
                    _voteButtons[i].Text = Loc.GetString("ui-vote-button-no-votes", ("text", entry.Text));
                }

                if (_vote.OurVote == i)
                    _voteButtons[i].Pressed = true;
            }
        }

        private void AttemptFollowVoteEntity()
        {
            if (_targetEntity != null)
            {
                var msg = new GhostWarpToTargetRequestEvent(_targetEntity.Value);
                _net.SendSystemNetworkMessage(msg);
            }
        }

        protected override Vector2 MeasureOverride(Vector2 availableSize)
        {
            if (_lobbyStyle)
            {
                // A large character console leaves less room for the sidebar on
                // small windows. Keep a usable content width instead of allowing
                // fixed margins to push the centered timer/bar outside the card.
                var inset = Math.Clamp((availableSize.X - 32) / 2, 0, LobbyConsoleTheme.ContentInset);
                Contents.Margin = new Thickness(inset, LobbyConsoleTheme.ContentInset);
            }
            return base.MeasureOverride(availableSize);
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            // Logger.Debug($"{_gameTiming.ServerTime}, {_vote.StartTime}, {_vote.EndTime}");

            var curTime = _gameTiming.RealTime;
            var timeLeft = _vote.EndTime - curTime;
            if (timeLeft < TimeSpan.Zero)
                timeLeft = TimeSpan.Zero;

            // Round up a second.
            timeLeft = TimeSpan.FromSeconds(Math.Ceiling(timeLeft.TotalSeconds));

            TimeLeftBar.Value = Math.Min(1, (float) ((curTime.TotalSeconds - _vote.StartTime.TotalSeconds) /
                                                     (_vote.EndTime.TotalSeconds - _vote.StartTime.TotalSeconds)));

            TimeLeftText.Text = $"{timeLeft:m\\:ss}";
        }
    }
}
