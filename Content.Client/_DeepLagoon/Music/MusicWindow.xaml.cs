using Content.Shared._DeepLagoon.Music;
using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._DeepLagoon.Music;

[GenerateTypedNameReferences]
public sealed partial class MusicWindow : FancyWindow
{
    public event Action<string, string>? OnAction;

    private readonly List<MusicTrack> _results = new();

    public MusicWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("dl-music-title");

        SearchButton.OnPressed += _ => Submit();
        SearchBar.OnTextEntered += _ => Submit();
        Results.OnItemSelected += args =>
        {
            if (args.ItemIndex < 0 || args.ItemIndex >= _results.Count)
                return;

            OnAction?.Invoke("play", _results[args.ItemIndex].Id);
        };

        PlayButton.OnPressed += _ => OnAction?.Invoke("resume", string.Empty);
        PauseButton.OnPressed += _ => OnAction?.Invoke("pause", string.Empty);
        StopButton.OnPressed += _ => OnAction?.Invoke("stop", string.Empty);
        NextButton.OnPressed += _ => OnAction?.Invoke("next", string.Empty);
        VolumeSlider.OnValueChanged += _ => OnAction?.Invoke("gain",
            VolumeSlider.Value.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture));
            }

    private void Submit() => OnAction?.Invoke("search", SearchBar.Text);

    public void SetResults(IReadOnlyList<MusicTrack> tracks, string statusText)
    {
        _results.Clear();
        _results.AddRange(tracks);
        Results.Clear();

        foreach (var track in tracks)
        {
            var artist = string.IsNullOrEmpty(track.Artist) ? Loc.GetString("dl-music-artist-unknown") : track.Artist;
            var suffix = track.Duration > 0f ? $" [{Format(track.Duration)}]" : string.Empty;
            Results.AddItem($"{track.Title} - {artist}{suffix}");
        }

        StatusLabel.Text = statusText;
    }

    public void SetState(string stateKey, MusicTrack? current, float position, float length, float gain, bool global,
        int listeners)
    {
        if (current == null)
        {
            CurrentLabel.Text = Loc.GetString("dl-music-nothing-playing");
        }
        else
        {
            var artist = string.IsNullOrEmpty(current.Artist) ? Loc.GetString("dl-music-artist-unknown") : current.Artist;
            CurrentLabel.Text =
                $"{current.Title} - {artist} - {Loc.GetString("dl-music-" + stateKey)} " +
                $"{Format(position)}/{Format(length)}";
        }

        Progress.Value = length > 0f ? Math.Clamp(position / length, 0f, 1f) : 0f;

        VolumeSlider.Value = gain;

        GlobalLabel.Text = global
            ? $"{Loc.GetString("dl-music-global")} - {Loc.GetString("dl-music-listeners")}: {listeners}"
            : string.Empty;
    }

    private static string Format(float seconds)
    {
        if (!float.IsFinite(seconds) || seconds < 0f)
            seconds = 0f;

        var total = (int) seconds;
        return $"{total / 60:D2}:{total % 60:D2}";
    }
}
