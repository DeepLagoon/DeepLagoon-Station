using Content.Shared._DeepLagoon.Mantis;
using Content.Shared.Psionics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._DeepLagoon.Mantis;

[GenerateTypedNameReferences]
public sealed partial class PsiRegistryUiFragment : BoxContainer
{

    public event Action<uint?>? OnRecordSelected;

    public event Action<PsionicsStatus, string?>? OnStatusRequested;

    private bool _canEdit;
    private uint? _selectedKey;

    private bool _isPopulating;

    public PsiRegistryUiFragment()
    {
        RobustXamlLoader.Load(this);

        Orientation = LayoutOrientation.Vertical;

        RecordListing.OnItemSelected += args =>
        {
            if (_isPopulating || RecordListing[args.ItemIndex].Metadata is not uint key)
                return;

            OnRecordSelected?.Invoke(key);
        };

        RecordListing.OnItemDeselected += _ =>
        {
            if (!_isPopulating)
                OnRecordSelected?.Invoke(null);
        };

        CleanButton.OnPressed += _ => Request(PsionicsStatus.Registered);
        SuspectedButton.OnPressed += _ => Request(PsionicsStatus.Suspected);
        AbusingButton.OnPressed += _ => Request(PsionicsStatus.Abusing);
        ResetButton.OnPressed += _ => Request(PsionicsStatus.None);
    }

    private void Request(PsionicsStatus status)
    {
        if (!_canEdit || _selectedKey == null)
            return;

        var reason = status == PsionicsStatus.None ? null : ReasonEdit.Text;

        OnStatusRequested?.Invoke(status, reason);
    }

    public void UpdateState(PsiRegistryUiState state)
    {
        _canEdit = state.CanEdit;
        _selectedKey = state.SelectedKey;

        NoRecords.Visible = state.Records.Count == 0;

        _isPopulating = true;
        RecordListing.Clear();
        foreach (var record in state.Records)
        {
            var item = RecordListing.AddItem(
                Loc.GetString("psi-registry-row", ("name", record.Name), ("status", StatusName(record.Status))));
            item.Metadata = record.Key;
            item.Selected = record.Key == state.SelectedKey;
        }

        _isPopulating = false;

        var selected = state.SelectedKey != null;
        PersonContainer.Visible = selected;
        RecordUnselected.Visible = !selected;

        SetButtonsDisabled(!_canEdit || !selected);

        AccessLabel.Text = _canEdit
            ? Loc.GetString("psi-registry-access-granted")
            : Loc.GetString("psi-registry-access-denied");

        if (state.SelectedKey is not { } key)
            return;

        foreach (var record in state.Records)
        {
            if (record.Key != key)
                continue;

            PersonName.Text = record.Name;
            PersonJob.Text = record.Job.Length == 0
                ? Loc.GetString("psi-registry-unknown-job")
                : record.Job;

            StatusLabel.Text = Loc.GetString("psi-registry-status-line", ("status", StatusName(record.Status)));
            ReasonLabel.Text = record.Reason is { } reason
                ? Loc.GetString("psi-registry-reason-line", ("reason", reason))
                : Loc.GetString("psi-registry-reason-none");
            break;
        }
    }

    private void SetButtonsDisabled(bool disabled)
    {
        CleanButton.Disabled = disabled;
        SuspectedButton.Disabled = disabled;
        AbusingButton.Disabled = disabled;
        ResetButton.Disabled = disabled;
        ReasonEdit.Editable = !disabled;
    }

    private static string StatusName(PsionicsStatus status)
    {
        return Loc.GetString("psi-registry-status-" + status.ToString().ToLowerInvariant());
    }
}
