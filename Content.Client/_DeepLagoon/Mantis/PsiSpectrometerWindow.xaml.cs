using Content.Shared._DeepLagoon.Mantis;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client.UserInterface.Controls;

namespace Content.Client._DeepLagoon.Mantis;

[GenerateTypedNameReferences]
public sealed partial class PsiSpectrometerWindow : FancyWindow
{
    public event Action? OnScan;
    public event Action<bool>? OnHunter;
    public event Action<bool>? OnMapOverlay;

    public PsiSpectrometerWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("psi-spectrometer-title");

        ScanButton.OnPressed += _ => OnScan?.Invoke();
        HunterCheck.OnToggled += args => OnHunter?.Invoke(args.Pressed);
        MapCheck.OnToggled += args => OnMapOverlay?.Invoke(args.Pressed);
    }

    public void UpdateState(PsiSpectrometerState state)
    {
        GlimmerLabel.Text = Loc.GetString("psi-spectrometer-glimmer", ("value", state.Glimmer));
        RangeLabel.Text = Loc.GetString("psi-spectrometer-range", ("range", MathF.Round(state.Range)));

        if (HunterCheck.Pressed != state.HunterMode)
            HunterCheck.Pressed = state.HunterMode;

        if (MapCheck.Pressed != state.MapOverlay)
            MapCheck.Pressed = state.MapOverlay;

        ScanButton.Disabled = !state.Ready;
        StatusLabel.Text = state.Ready
            ? Loc.GetString("psi-spectrometer-ready")
            : Loc.GetString("psi-spectrometer-recharging");

        Results.RemoveAllChildren();

        if (state.Signatures.Count == 0)
        {
            Results.AddChild(new Label { Text = Loc.GetString("psi-spectrometer-empty") });
            return;
        }

        foreach (var signature in state.Signatures)
        {
            Results.AddChild(new Label
            {
                Text = Loc.GetString("psi-spectrometer-line",
                    ("type", Loc.GetString("psi-spectrometer-type-" + signature.Type.ToString().ToLowerInvariant())),
                    ("sector", Loc.GetString("psi-spectrometer-sector-" + signature.Sector.ToString().ToLowerInvariant())),
                    ("name", signature.Name),
                    ("intensity", (int) (signature.Intensity * 100))),
            });
        }
    }
}
