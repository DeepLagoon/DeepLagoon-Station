using Content.Client.UserInterface.Controls;
using Content.Shared._DeepLagoon.BodyInsurance;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._DeepLagoon.BodyInsurance;

[GenerateTypedNameReferences]
public sealed partial class BodyInsuranceWindow : FancyWindow
{
    public event Action? PurchaseRequested;

    public BodyInsuranceWindow()
    {
        RobustXamlLoader.Load(this);

        Title = Loc.GetString(
            "body-insurance-window-title");

        PurchaseButton.OnPressed += _ =>
            PurchaseRequested?.Invoke();
    }

    public void UpdateState(BodyInsuranceUiState state)
    {
        // Стоимость страхования тела.
        PriceLabel.Text = Loc.GetString(
            "body-insurance-price",
            ("price", state.Price.ToString("N0")));

        // Стоимость подписки на текущий раунд.
        SubscriptionPriceLabel.Text = Loc.GetString(
            "body-insurance-subscription-price",
            ("price", state.SubscriptionPrice));

        // Статус подписки.
        SubscriptionStatusLabel.Text = Loc.GetString(
            state.HasSubscription
                ? "body-insurance-subscription-active"
                : "body-insurance-subscription-inactive");

        SubscriptionStatusLabel.FontColorOverride =
            state.HasSubscription
                ? Color.LightGreen
                : Color.IndianRed;

        // Количество покупок страховки.
        PurchaseCountLabel.Text = Loc.GetString(
            "body-insurance-purchase-count",
            ("count", state.PurchaseCount));

        // Статус страхования тела.
        InsuranceStatusLabel.Text = Loc.GetString(
            state.Insured
                ? "body-insurance-status-active"
                : "body-insurance-status-inactive");

        InsuranceStatusLabel.FontColorOverride =
            state.Insured
                ? Color.LightGreen
                : Color.IndianRed;

        PurchaseButton.Disabled = !state.CanPurchase;

        // Название кнопки зависит от статуса подписки.
        PurchaseButton.Text = Loc.GetString(
            state.Insured
                ? "body-insurance-active"
                : state.HasSubscription
                    ? "body-insurance-purchase"
                    : "body-insurance-purchase-with-subscription");
    }
}
