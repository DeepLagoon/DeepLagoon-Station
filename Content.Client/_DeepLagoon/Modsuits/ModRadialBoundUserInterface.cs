using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._DeepLagoon.Modsuits;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.Input;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;

namespace Content.Client._DeepLagoon.Modsuits;

public sealed class ModRadialBoundUserInterface(EntityUid owner, Enum key) : BoundUserInterface(owner, key)
{
    private ModRadialMenu? _menu;

    protected override void Open()
    {
        base.Open();
        _menu = this.CreateWindow<ModRadialMenu>();
        _menu.OnSelect += selection => SendMessage(new ModRadialSelection(selection));
        var mouse = IoCManager.Resolve<IInputManager>().MouseScreenPosition.Position;
        _menu.OpenCenteredAt(mouse / IoCManager.Resolve<IClyde>().ScreenSize);
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is ModRadialState radial)
            _menu?.SetChoices(radial.Choices);
    }
}

public sealed class ModRadialMenu : RadialMenu
{
    private readonly RadialContainer _choices = new();
    private readonly SpriteSystem _sprites = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
    public event Action<int>? OnSelect;

    public ModRadialMenu()
    {
        CloseButtonStyleClass = "RadialMenuCloseButton";
        AddChild(_choices);
    }

    public void SetChoices(ModRadialChoice[] choices)
    {
        _choices.RemoveAllChildren();
        foreach (var choice in choices)
        {
            var button = new RadialMenuTextureButton
            {
                SetSize = new Vector2(48, 48),
                ToolTip = choice.Name,
                StyleClasses = { "RadialMenuButton" },
            };
            button.AddChild(new TextureRect
            {
                Texture = _sprites.Frame0(choice.Icon),
                Modulate = choice.Selected ? Color.White : Color.FromHex("#B6C3D4"),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                SetSize = new Vector2(36, 36),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                MouseFilter = MouseFilterMode.Ignore,
            });
            button.OnButtonUp += _ => OnSelect?.Invoke(choice.Id);
            _choices.AddChild(button);
        }
    }
}
