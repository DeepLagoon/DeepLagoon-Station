using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._DeepLagoon.Modsuits;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Localization;

namespace Content.Client._DeepLagoon.Modsuits;

public sealed class ModHardlightBoundUserInterface(EntityUid owner, Enum key) : BoundUserInterface(owner, key)
{
    private ModHardlightWindow? _window;
    private ModHardlightVisualSystem? _visuals;
    private EntityUid? _wearer;
    private EntityUid? _preview;

    protected override void Open()
    {
        base.Open();
        _visuals = EntMan.System<ModHardlightVisualSystem>();
        _wearer = IoCManager.Resolve<IPlayerManager>().LocalEntity;
        _preview = _visuals.CreatePreview(_wearer);
        _window = this.CreateWindow<ModHardlightWindow>();
        _window.OnApply += (color, effect) => SendMessage(new ModHardlightStyleMessage(color.ToHexNoAlpha(), effect));
        _window.OnPreview += (parts, color, effect) => _visuals.UpdatePreview(_wearer, _preview, parts, color, effect);
        _window.ShowPreview(_preview);
        _window.OpenCentered();
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is ModHardlightState hardlight)
            _window?.Update(hardlight);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _visuals?.DeletePreview(_preview);
        base.Dispose(disposing);
    }
}

public sealed class ModHardlightWindow : FancyWindow
{
    private readonly ColorSelectorSliders _color = new() { HorizontalExpand = true };
    private readonly SpriteView _model = new()
    {
        SetSize = new Vector2(265, 250),
        Scale = new Vector2(3),
        HorizontalAlignment = HAlignment.Center,
        OverrideDirection = Direction.South,
    };
    private readonly Dictionary<ModHardlightEffect, Button> _effects = new();
    private readonly Label _emptyField = new() { Text = Loc.GetString("mod-hardlight-preview-empty") };
    private ModHardlightState? _saved;
    private ModHardlightEffect _effect;

    public event Action<Color, ModHardlightEffect>? OnApply;
    public event Action<ModHardlightParts, Color, ModHardlightEffect>? OnPreview;

    public ModHardlightWindow()
    {
        Title = Loc.GetString("mod-hardlight-title");
        MinSize = new Vector2(570, 370);
        SetSize = new Vector2(680, 450);
        var layout = new BoxContainer { SeparationOverride = 12, Margin = new Thickness(10) };
        var scroll = new ScrollContainer { VerticalExpand = true, HScrollEnabled = false };
        scroll.AddChild(layout);
        ContentsContainer.AddChild(scroll);

        var preview = Column();
        preview.HorizontalExpand = true;
        layout.AddChild(preview);
        preview.AddChild(new Label { Text = Loc.GetString("mod-hardlight-preview") });
        preview.AddChild(_model);
        var directions = new BoxContainer { HorizontalAlignment = HAlignment.Center, SeparationOverride = 4 };
        foreach (var direction in new[] { Direction.South, Direction.West, Direction.North, Direction.East })
        {
            var button = new Button { Text = Loc.GetString($"mod-hardlight-direction-{direction.ToString().ToLowerInvariant()}") };
            button.OnPressed += _ => _model.OverrideDirection = direction;
            directions.AddChild(button);
        }
        preview.AddChild(directions);
        var zoom = new Slider { MinValue = 1, MaxValue = 5, Value = 3, HorizontalExpand = true };
        zoom.OnValueChanged += args => _model.Scale = new Vector2((float) args.Value);
        preview.AddChild(new Label { Text = Loc.GetString("mod-hardlight-zoom") });
        preview.AddChild(zoom);
        preview.AddChild(_emptyField);

        var settings = Column();
        settings.MinWidth = 235;
        layout.AddChild(settings);
        settings.AddChild(new Label { Text = Loc.GetString("mod-hardlight-animation") });
        foreach (var effect in Enum.GetValues<ModHardlightEffect>())
        {
            var button = new Button
            {
                Text = Loc.GetString($"mod-hardlight-effect-{effect.ToString().ToLowerInvariant()}"),
                ToggleMode = true,
            };
            button.OnPressed += _ => SelectEffect(effect);
            _effects.Add(effect, button);
            settings.AddChild(button);
        }

        settings.AddChild(new Label { Text = Loc.GetString("mod-hardlight-color") });
        settings.AddChild(_color);
        _color.OnColorChanged += _ => RefreshPreview();

        var apply = new Button { Text = Loc.GetString("mod-hardlight-apply") };
        apply.OnPressed += _ => OnApply?.Invoke(_color.Color, _effect);
        settings.AddChild(apply);

        var reset = new Button { Text = Loc.GetString("mod-hardlight-reset") };
        reset.OnPressed += _ => ResetStyle();
        settings.AddChild(reset);
    }

    public void ShowPreview(EntityUid? wearer) => _model.SetEntity(wearer);

    public void Update(ModHardlightState state)
    {
        var reset = _saved == null || _saved.Color != state.Color || _saved.Effect != state.Effect;
        _saved = state;
        if (reset)
            ResetStyle();
        else
            RefreshPreview();
    }

    private void ResetStyle()
    {
        if (_saved is not {} state)
            return;

        _color.Color = state.Color;
        SelectEffect(state.Effect);
    }

    private void SelectEffect(ModHardlightEffect effect)
    {
        _effect = effect;
        foreach (var (id, button) in _effects)
            button.Pressed = id == effect;

        RefreshPreview();
    }

    private void RefreshPreview()
    {
        var parts = _saved?.Parts ?? ModHardlightParts.None;
        _emptyField.Visible = parts == ModHardlightParts.None;
        OnPreview?.Invoke(parts, _color.Color, _effect);
    }

    private static BoxContainer Column() =>
        new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 5 };
}
