namespace Content.Client._DeepLagoon.Modsuits;

public sealed class ModBoundUserInterface(EntityUid owner, Enum key) : BoundUserInterface(owner, key)
{
    private ModWindow? _window;

    protected override void Open()
    {
        base.Open();
        _window = this.CreateWindow<ModWindow>();
        _window.OnCommand += SendMessage;
        _window.OpenCentered();
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is ModUiState modState)
            _window?.Update(modState);
    }
}

public sealed partial class ModWindow : FancyWindow
{
    private readonly Label _power = new();
    private readonly ProgressBar _chargeBar = new() { MinValue = 0, MaxValue = 100 };
    private readonly Label _cover = new();
    private readonly Label _selected = new();
    private readonly Label _wearer = new();
    private readonly Label _complexity = new();
    private readonly Label _cell = new();
    private readonly Label _info = new();
    private readonly BoxContainer _parts = Column();
    private readonly BoxContainer _parameters = Column();
    private readonly BoxContainer _hardware = Column();
    private readonly BoxContainer _infoSection = Column();
    private readonly BoxContainer _moduleSection = Column();
    private readonly Button _hardlight = new() { Text = Loc.GetString("mod-hardlight-title") };
    private readonly Dictionary<NetEntity, (Collapsible Row, Label Cooldown)> _moduleRows = new();
    private readonly Label _suitStatus = new();
    private readonly Label _linkStatus = new();
    private readonly Label _address = new();
    private readonly Button _toggleSuit = new();
    private readonly BoxContainer _modules = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
    private readonly BoxContainer _contacts = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
    private readonly LineEdit _name = new() { HorizontalExpand = true };
    private readonly LineEdit _frequency = new() { HorizontalExpand = true };
    private readonly Button _rename = new() { Text = Loc.GetString("mod-link-rename") };
    private readonly Button _setFrequency = new() { Text = Loc.GetString("mod-link-tune") };
    private ModUiState? _previous;
    private static readonly StyleBoxFlat Charged = new(Color.FromHex("#55AD73"));
    private static readonly StyleBoxFlat LowCharge = new(Color.FromHex("#CF9A4D"));
    private static readonly StyleBoxFlat EmptyCharge = new(Color.FromHex("#C35A63"));

    public event Action<ModUiMessage>? OnCommand;

    public ModWindow()
    {
        Title = Loc.GetString("mod-control-title");
        MinSize = new Vector2(400, 300);
        SetSize = new Vector2(400, 525);

        var scroll = new ScrollContainer { VerticalExpand = true, HScrollEnabled = false };
        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 8,
            Margin = new Thickness(10),
            HorizontalExpand = true,
        };
        scroll.AddChild(body);
        ContentsContainer.AddChild(scroll);
        InitializeTgui(scroll);

        body.AddChild(_parameters);
        body.AddChild(_hardware);
        body.AddChild(_infoSection);
        body.AddChild(_moduleSection);
        _parameters.AddChild(Section("mod-section-parameters",
            LabeledRow("mod-panel-label-status", _suitStatus, _toggleSuit),
            Collapsed("MODlink", _address, Row(_name, _rename), Row(_frequency, _setFrequency), _linkStatus, _contacts),
            LabeledRow("mod-panel-label-cover", _cover),
            LabeledRow("mod-panel-label-selected", _selected),
            LabeledRow("mod-panel-label-complexity", _complexity),
            LabeledRow("mod-panel-label-wearer", _wearer),
            _hardlight));
        _hardware.AddChild(Section("mod-section-hardware", Collapsed(Loc.GetString("mod-section-parts"), _parts),
            Collapsed(Loc.GetString("mod-section-cell"), _cell, _power, _chargeBar)));
        _infoSection.AddChild(Section("mod-section-info", _info));
        _moduleSection.AddChild(Section("mod-section-modules", _modules));

        _hardlight.OnPressed += _ => Send(ModOperation.OpenHardlightStyle);
        _toggleSuit.OnPressed += _ => Send(ModOperation.ToggleSuit);
        _rename.OnPressed += _ => Send(ModOperation.Rename, text: _name.Text);
        _setFrequency.OnPressed += _ => Send(ModOperation.SetFrequency, text: _frequency.Text);
        _name.OnTextEntered += _ => Send(ModOperation.Rename, text: _name.Text);
        _frequency.OnTextEntered += _ => Send(ModOperation.SetFrequency, text: _frequency.Text);
    }

    public void Update(ModUiState state)
    {
        var old = _previous;
        _previous = state;
        _power.Text = state.Charge < 0 ? Loc.GetString("mod-power-empty") :
            Loc.GetString("mod-power-charge", ("charge", state.Charge));

        Title = state.Control ? Loc.GetString("mod-panel-title") : "MODlink";
        PublishTgui(state);
        _suitStatus.Parent!.Visible = _cover.Parent!.Visible = _selected.Parent!.Visible =
            _complexity.Parent!.Visible = _wearer.Parent!.Visible = state.Control;
        _infoSection.Visible = _moduleSection.Visible = _hardware.Visible = state.Control;
        _power.Visible = _chargeBar.Visible = state.Charge >= 0;
        _chargeBar.Value = state.Charge < 0 ? 0 : state.Charge;
        _chargeBar.ForegroundStyleBoxOverride = state.Charge switch
        {
            >= 60 => Charged,
            >= 30 => LowCharge,
            _ => EmptyCharge,
        };
        _hardlight.Visible = state.Control && state.WearableControls;
        _toggleSuit.Visible = state.Control && state.WearableControls;
        _toggleSuit.Disabled = state.Busy || state.Service;
        _toggleSuit.Text = Loc.GetString(state.Active ? "mod-suit-deactivate" : "mod-suit-activate");
        _suitStatus.Text = Loc.GetString(state.Busy ? "mod-panel-label-busy" :
            state.Active ? "mod-panel-label-active" : "mod-panel-label-idle");
        _cover.Text = Loc.GetString(state.Service ? "mod-panel-label-open" : "mod-panel-label-closed");
        _selected.Text = OrNone(state.Details.SelectedModule);
        _complexity.Text = $"{state.Complexity} ({state.Capacity})";
        _wearer.Text = OrNone(state.Details.Wearer);
        _cell.Text = string.IsNullOrEmpty(state.Details.Cell)
            ? Loc.GetString("mod-power-empty")
            : Loc.GetString("mod-panel-cell", ("value", state.Details.Cell));
        _info.Text = state.Details.BodyTemperature is {} temperature
            ? Loc.GetString("mod-panel-body-temperature", ("temperature", temperature))
            : Loc.GetString("mod-panel-no-info");

        if (old == null || old.Details.Name != state.Details.Name || !old.Parts.AsSpan().SequenceEqual(state.Parts))
            UpdateParts(state);

        if (old == null || old.Active != state.Active || old.Busy != state.Busy || old.Service != state.Service ||
            old.WearableControls != state.WearableControls ||
            !ModulesMatch(old.Modules, state.Modules))
            UpdateModules(state);

        _address.Text = Loc.GetString("mod-link-address", ("number", state.Number), ("frequency", state.Frequency));
        if (old?.Label != state.Label)
            _name.Text = state.Label;
        if (old?.Frequency != state.Frequency)
            _frequency.Text = state.Frequency.ToString();

        _name.Editable = state.WearableControls;
        _rename.Disabled = !state.WearableControls;
        _frequency.Editable = state.CanSetFrequency;
        _setFrequency.Disabled = !state.CanSetFrequency;
        if (old == null || old.Call != state.Call || old.Peer != state.Peer ||
            !old.Contacts.AsSpan().SequenceEqual(state.Contacts))
            UpdateContacts(state);
    }

    private void UpdateParts(ModUiState state)
    {
        _parts.RemoveAllChildren();
        _parts.AddChild(new Label { Text = Loc.GetString("mod-panel-part-control", ("value", state.Details.Name)) });
        foreach (var slot in new[] { "head", "outerClothing", "gloves", "shoes" })
        {
            ModHardwarePart? part = null;
            foreach (var entry in state.Parts)
            {
                if (entry.Slot == slot)
                    part = entry;
            }
            var name = Loc.GetString($"mod-panel-part-{slot.ToLowerInvariant()}");
            _parts.AddChild(new Label { Text = part == null ? $"{name} · {OrNone(string.Empty)}" :
                Loc.GetString(part.Deployed ? "mod-panel-part-deployed" : "mod-panel-part-stowed",
                    ("slot", name), ("name", part.Name)) });
        }
    }

    private bool ModulesMatch(ModModuleEntry[] old, ModModuleEntry[] current)
    {
        if (old.Length != current.Length)
            return false;

        for (var i = 0; i < old.Length; i++)
        {
            if (old[i] with { Cooldown = current[i].Cooldown } != current[i])
                return false;

            if (_moduleRows.TryGetValue(current[i].Id, out var row))
                row.Cooldown.Text = ModuleCooldown(current[i]);
        }
        return true;
    }

    private static string ModuleCooldown(ModModuleEntry module) =>
        Loc.GetString("mod-panel-module-cooldown", ("current", module.Cooldown), ("delay", module.UseDelay));

    private void UpdateModules(ModUiState state)
    {
        var expanded = new HashSet<NetEntity>();
        foreach (var (id, entry) in _moduleRows)
        {
            if (entry.Row.BodyVisible)
                expanded.Add(id);
        }

        _moduleRows.Clear();
        _modules.RemoveAllChildren();
        if (state.Modules.Length == 0)
            _modules.AddChild(new Label { Text = Loc.GetString("mod-panel-no-modules") });
        foreach (var module in state.Modules)
        {
            var row = Row();
            var cooldown = new Label { Text = ModuleCooldown(module) };
            var details = Column(
                Row(
                    ModuleStat("mod-panel-complexity-short", new Label { Text = $"{module.Complexity}/{state.Capacity}" }),
                    ModuleStat("mod-panel-idle-draw", new Label { Text = "0" }),
                    ModuleStat("mod-panel-active-draw", new Label { Text = "0" }),
                    ModuleStat("mod-panel-use-draw", new Label { Text = $"{module.UseCharge:g}" }),
                    ModuleStat("mod-panel-cooldown-short", cooldown)),
                row);
            if (module.Usable)
            {
                var toggle = CommandButton(module.Active ? "mod-module-stop" : "mod-module-use",
                    ModOperation.ToggleModule, module.Id);
                toggle.Disabled = module.RequiresPower && (!state.WearableControls || !state.Active || state.Busy);
                row.AddChild(toggle);
                var pin = CommandButton(module.Pinned ? "mod-panel-pinned" : "mod-panel-pin", ModOperation.PinModule, module.Id);
                pin.Disabled = module.Pinned || !state.WearableControls;
                row.AddChild(pin);
            }
            else
                row.AddChild(new Label { Text = Loc.GetString(module.Active ? "mod-module-enabled" : "mod-module-passive") });

            if (state.Service)
                row.AddChild(CommandButton("mod-module-remove", ModOperation.RemoveModule, module.Id));

            if (module.TargetTemperature is {} targetTemperature)
            {
                var target = new LineEdit { Text = targetTemperature.ToString(), Editable = state.WearableControls,
                    HorizontalExpand = true };
                var apply = new Button { Text = Loc.GetString("mod-module-set-temperature"), Disabled = !state.WearableControls };
                apply.OnPressed += _ => Send(ModOperation.ConfigureModule, module.Id, target.Text);
                target.OnTextEntered += _ => Send(ModOperation.ConfigureModule, module.Id, target.Text);
                details.AddChild(Row(new Label { Text = Loc.GetString("mod-module-temperature") }, target, apply));
            }
            var description = new RichTextLabel { HorizontalExpand = true };
            description.SetMessage(Robust.Shared.Utility.FormattedMessage.FromUnformatted(module.Description));
            details.AddChild(description);
            var entry = Collapsed(module.Name, details);
            entry.BodyVisible = expanded.Contains(module.Id);
            _moduleRows.Add(module.Id, (entry, cooldown));
            _modules.AddChild(entry);
        }
    }

    private void UpdateContacts(ModUiState state)
    {
        _contacts.RemoveAllChildren();
        _linkStatus.Text = state.Call switch
        {
            ModCallState.Dialing => Loc.GetString("mod-link-dialing", ("peer", state.Peer)),
            ModCallState.Incoming => Loc.GetString("mod-link-incoming", ("peer", state.Peer)),
            ModCallState.Connected => Loc.GetString("mod-link-connected", ("peer", state.Peer)),
            _ => Loc.GetString(state.Contacts.Length == 0 ? "mod-link-empty" : "mod-link-available"),
        };

        if (state.Call != ModCallState.Idle)
        {
            var row = Row();
            if (state.Call == ModCallState.Incoming)
                row.AddChild(CommandButton("mod-link-accept", ModOperation.Accept));
            row.AddChild(CommandButton(state.Call == ModCallState.Incoming ? "mod-link-decline" : "mod-link-end",
                ModOperation.End));
            _contacts.AddChild(row);
            return;
        }

        foreach (var contact in state.Contacts)
        {
            var name = new Label { Text = contact.Name, HorizontalExpand = true };
            _contacts.AddChild(Row(name, CommandButton("mod-link-call", ModOperation.Call, contact.Id)));
        }
    }

    private static Control ModuleStat(LocId label, Label value)
    {
        var title = Loc.GetString(label);
        var stat = Column(new Label { Text = title, ToolTip = title }, value);
        stat.HorizontalExpand = true;
        return stat;
    }

    private static string OrNone(string value) => string.IsNullOrEmpty(value) ? Loc.GetString("mod-panel-none") : value;

    private static PanelContainer Section(LocId title, params Control[] content)
    {
        var box = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#272729"),
                ContentMarginTopOverride = 7, ContentMarginBottomOverride = 7,
                ContentMarginLeftOverride = 8, ContentMarginRightOverride = 8 }
        };
        var children = Column(new Label { Text = Loc.GetString(title), FontColorOverride = Color.FromHex("#EEEEEE") });
        foreach (var child in content)
            children.AddChild(child);
        box.AddChild(children);
        return box;
    }

    private static Collapsible Collapsed(string title, params Control[] children)
    {
        var body = new CollapsibleBody();
        body.AddChild(Column(children));
        return new Collapsible(title, body);
    }

    private static BoxContainer Column(params Control[] contents)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
        foreach (var child in contents)
            box.AddChild(child);
        return box;
    }

    private static BoxContainer LabeledRow(LocId label, Control value, Control? action = null)
    {
        value.HorizontalExpand = true;
        var row = Row(new Label
        {
            Text = Loc.GetString(label),
            MinWidth = 125,
            FontColorOverride = Color.FromHex("#AAAAAA"),
        }, value);
        if (action != null)
            row.AddChild(action);
        return row;
    }

    private static BoxContainer Row(params Control[] contents)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        foreach (var child in contents)
            row.AddChild(child);
        return row;
    }

    private Button CommandButton(LocId text, ModOperation command, NetEntity target = default)
    {
        var button = new Button { Text = Loc.GetString(text) };
        button.OnPressed += _ => Send(command, target);
        return button;
    }

    private void Send(ModOperation command, NetEntity target = default, string text = "")
    {
        OnCommand?.Invoke(new ModUiMessage(command, target, text));
    }
}
