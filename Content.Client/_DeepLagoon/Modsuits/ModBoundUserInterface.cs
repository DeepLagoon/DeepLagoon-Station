using Content.Client.Administration.UI.CustomControls;
using Content.Client.UserInterface.Controls;
using Content.Shared._DeepLagoon.Modsuits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Localization;
using System.Numerics;

namespace Content.Client._DeepLagoon.Modsuits;

public sealed class ModBoundUserInterface(EntityUid owner, Enum key) : BoundUserInterface(owner, key)
{
    private ModWindow? _window;

    protected override void Open()
    {
        base.Open();
        _window = this.CreateWindow<ModWindow>();
        _window.OnCommand += SendMessage;
        _window.OpenCentered();
    }

    protected override void UpdateState(BoundUserInterfaceState state)
    {
        base.UpdateState(state);
        if (state is ModUiState modState)
            _window?.Update(modState);
    }
}

public sealed class ModWindow : FancyWindow
{
    private readonly Label _power = new();
    private readonly Label _suitStatus = new();
    private readonly Label _linkStatus = new();
    private readonly Label _address = new();
    private readonly Button _toggleSuit = new();
    private readonly BoxContainer _modules = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
    private readonly BoxContainer _contacts = new() { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4 };
    private readonly LineEdit _name = new() { HorizontalExpand = true };
    private readonly LineEdit _frequency = new() { HorizontalExpand = true };
    private readonly Button _rename = new() { Text = Loc.GetString("mod-link-rename") };
    private readonly Button _setFrequency = new() { Text = Loc.GetString("mod-link-tune") };
    private ModUiState? _previous;

    public event Action<ModUiMessage>? OnCommand;

    public ModWindow()
    {
        Title = Loc.GetString("mod-control-title");
        MinSize = new Vector2(420, 300);
        SetSize = new Vector2(490, 540);

        var scroll = new ScrollContainer { VerticalExpand = true, HScrollEnabled = false };
        var body = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 8,
            Margin = new Thickness(10),
            HorizontalExpand = true,
        };
        scroll.AddChild(body);
        ContentsContainer.AddChild(scroll);

        body.AddChild(_power);
        body.AddChild(Row(_suitStatus, _toggleSuit));
        body.AddChild(_modules);
        body.AddChild(new HSeparator());
        body.AddChild(_address);
        body.AddChild(Row(_name, _rename));
        body.AddChild(Row(_frequency, _setFrequency));
        body.AddChild(_linkStatus);
        body.AddChild(_contacts);

        _toggleSuit.OnPressed += _ => Send(ModOperation.ToggleSuit);
        _rename.OnPressed += _ => Send(ModOperation.Rename, text: _name.Text);
        _setFrequency.OnPressed += _ => Send(ModOperation.SetFrequency, text: _frequency.Text);
        _name.OnTextEntered += _ => Send(ModOperation.Rename, text: _name.Text);
        _frequency.OnTextEntered += _ => Send(ModOperation.SetFrequency, text: _frequency.Text);
    }

    public void Update(ModUiState state)
    {
        var old = _previous;
        _previous = state;
        _power.Text = state.Charge < 0 ? Loc.GetString("mod-power-empty") :
            Loc.GetString("mod-power-charge", ("charge", state.Charge));

        _suitStatus.Visible = state.Control;
        _suitStatus.HorizontalExpand = true;
        _modules.Visible = state.Control;
        _toggleSuit.Visible = state.Control && state.WearableControls;
        _toggleSuit.Disabled = state.Busy || state.Service;
        _toggleSuit.Text = Loc.GetString(state.Active ? "mod-suit-deactivate" : "mod-suit-activate");
        _suitStatus.Text = Loc.GetString(
            state.Busy ? "mod-suit-busy" : state.Active ? "mod-suit-active" : state.Service ? "mod-suit-service" : "mod-suit-idle",
            ("used", state.Complexity), ("capacity", state.Capacity));

        if (old == null || old.Active != state.Active || old.Busy != state.Busy || old.Service != state.Service ||
            old.WearableControls != state.WearableControls ||
            !old.Modules.AsSpan().SequenceEqual(state.Modules))
            UpdateModules(state);

        _address.Text = Loc.GetString("mod-link-address", ("number", state.Number), ("frequency", state.Frequency));
        if (old?.Label != state.Label)
            _name.Text = state.Label;
        if (old?.Frequency != state.Frequency)
            _frequency.Text = state.Frequency.ToString();

        _name.Editable = state.WearableControls;
        _rename.Disabled = !state.WearableControls;
        _frequency.Editable = state.CanSetFrequency;
        _setFrequency.Disabled = !state.CanSetFrequency;
        if (old == null || old.Call != state.Call || old.Peer != state.Peer ||
            !old.Contacts.AsSpan().SequenceEqual(state.Contacts))
            UpdateContacts(state);
    }

    private void UpdateModules(ModUiState state)
    {
        _modules.RemoveAllChildren();
        foreach (var module in state.Modules)
        {
            var text = new Label { Text = Loc.GetString("mod-module-row",
                ("name", module.Name), ("complexity", module.Complexity)), HorizontalExpand = true };
            var row = Row(text);
            if (module.Usable)
            {
                var toggle = CommandButton(module.Active ? "mod-module-stop" : "mod-module-use",
                    ModOperation.ToggleModule, module.Id);
                toggle.Disabled = module.RequiresPower && (!state.WearableControls || !state.Active || state.Busy);
                row.AddChild(toggle);
            }
            else
                row.AddChild(new Label { Text = Loc.GetString(module.Active ? "mod-module-enabled" : "mod-module-passive") });

            if (state.Service)
                row.AddChild(CommandButton("mod-module-remove", ModOperation.RemoveModule, module.Id));

            _modules.AddChild(row);
            if (module.TargetTemperature is {} targetTemperature)
            {
                var target = new LineEdit { Text = targetTemperature.ToString(), Editable = state.WearableControls,
                    HorizontalExpand = true };
                var apply = new Button { Text = Loc.GetString("mod-module-set-temperature"), Disabled = !state.WearableControls };
                apply.OnPressed += _ => Send(ModOperation.ConfigureModule, module.Id, target.Text);
                target.OnTextEntered += _ => Send(ModOperation.ConfigureModule, module.Id, target.Text);
                _modules.AddChild(Row(new Label { Text = Loc.GetString("mod-module-temperature") }, target, apply));
            }
        }
    }

    private void UpdateContacts(ModUiState state)
    {
        _contacts.RemoveAllChildren();
        _linkStatus.Text = state.Call switch
        {
            ModCallState.Dialing => Loc.GetString("mod-link-dialing", ("peer", state.Peer)),
            ModCallState.Incoming => Loc.GetString("mod-link-incoming", ("peer", state.Peer)),
            ModCallState.Connected => Loc.GetString("mod-link-connected", ("peer", state.Peer)),
            _ => Loc.GetString(state.Contacts.Length == 0 ? "mod-link-empty" : "mod-link-available"),
        };

        if (state.Call != ModCallState.Idle)
        {
            var row = Row();
            if (state.Call == ModCallState.Incoming)
                row.AddChild(CommandButton("mod-link-accept", ModOperation.Accept));
            row.AddChild(CommandButton(state.Call == ModCallState.Incoming ? "mod-link-decline" : "mod-link-end",
                ModOperation.End));
            _contacts.AddChild(row);
            return;
        }

        foreach (var contact in state.Contacts)
        {
            var name = new Label { Text = contact.Name, HorizontalExpand = true };
            _contacts.AddChild(Row(name, CommandButton("mod-link-call", ModOperation.Call, contact.Id)));
        }
    }

    private static BoxContainer Row(params Control[] contents)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        foreach (var child in contents)
            row.AddChild(child);
        return row;
    }

    private Button CommandButton(LocId text, ModOperation command, NetEntity target = default)
    {
        var button = new Button { Text = Loc.GetString(text) };
        button.OnPressed += _ => Send(command, target);
        return button;
    }

    private void Send(ModOperation command, NetEntity target = default, string text = "")
    {
        OnCommand?.Invoke(new ModUiMessage(command, target, text));
    }
}
