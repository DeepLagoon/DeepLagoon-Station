using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._DeepLagoon.Bitrunning;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._DeepLagoon.Bitrunning;

[GenerateTypedNameReferences]
public sealed partial class BitrunWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private BitrunUiState? _state;
    private int? _personalCredits;
    private int? _personalResearchPoints;
    private int? _shownSeconds;
    private bool _preparing;

    public event Action<BitrunUiMessage>? ActionRequested;

    public BitrunWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        DomainChoice.OnItemSelected += args =>
        {
            DomainChoice.SelectId(args.Id);
            UpdateDomainDetails();
        };
        ResearchChoice.OnItemSelected += args =>
        {
            if (_state is { } state && args.Id > 0 && args.Id <= state.ResearchServers.Length)
                Request(BitrunUiAction.BindResearch, target: state.ResearchServers[args.Id - 1].Entity);
        };
        SessionChoice.OnItemSelected += args =>
        {
            if (args.Id != SessionChoice.SelectedId)
                SideChoice.SelectId(0);
            SessionChoice.SelectId(args.Id);
            UpdateSessionDetails();
        };
        SideChoice.AddItem(Loc.GetString("bitrun-ui-choose-side"), 0);
        SideChoice.SetItemDisabled(0, true);
        SideChoice.AddItem(Loc.GetString("bitrun-side-attackers"), 1);
        SideChoice.AddItem(Loc.GetString("bitrun-side-defenders"), 2);
        SideChoice.OnItemSelected += args =>
        {
            SideChoice.SelectId(args.Id);
            UpdateSessionDetails();
        };
        LoadoutChoice.OnItemSelected += args =>
        {
            if (_state is { } state && args.Id >= 0 && args.Id < state.Loadouts.Length)
                Request(BitrunUiAction.SelectLoadout, state.Loadouts[args.Id]);
        };
        ShopChoice.OnItemSelected += args =>
        {
            ShopChoice.SelectId(args.Id);
            UpdateShop();
        };
        StartButton.OnPressed += _ =>
        {
            if (SelectedDomain() is { } domain)
                Request(BitrunUiAction.Start, domain.Id);
        };
        RandomButton.OnPressed += _ => Request(BitrunUiAction.Random);
        StopButton.OnPressed += _ =>
        {
            if (SelectedSession() is { } session)
                Request(BitrunUiAction.Stop, session: session.Id);
        };
        EnterButton.OnPressed += _ =>
        {
            if (SelectedSession() is { } session && SelectedSide() is { } side)
                Request(BitrunUiAction.Enter, target: session.Server, side: side, session: session.Id);
        };
        EjectButton.OnPressed += _ => Request(BitrunUiAction.Eject);
        BuyButton.OnPressed += _ =>
        {
            if (SelectedShopItem() is { } item)
                Request(BitrunUiAction.Buy, item.Id);
        };
    }

    public void SetState(BitrunUiState state, bool preparing)
    {
        var previous = _state;
        var selectedDomain = SelectedDomain()?.Id;
        var selectedSession = SelectedSession()?.Id;
        var selectedItem = SelectedShopItem()?.Id;
        _state = state;
        _preparing = preparing;

        ConsolePanel.Visible = state.Mode == BitrunUiMode.Console;
        PodPanel.Visible = state.Mode == BitrunUiMode.Pod;
        VendorPanel.Visible = state.Mode == BitrunUiMode.Vendor;
        Title = Loc.GetString(state.Mode switch
        {
            BitrunUiMode.Pod => "bitrun-ui-outfits",
            BitrunUiMode.Vendor => "bitrun-ui-shop",
            _ => "bitrun-ui-title",
        });

        var status = state.Status ?? Loc.GetString("bitrun-ui-ready");
        if (preparing || state.Mode == BitrunUiMode.Pod && state.Sessions is [{ Waiting: true }] && state.OccupiedSide != null)
            status += "\n" + Loc.GetString("bitrun-ui-pod-move-to-exit");
        StatusText.SetMessage(FormattedMessage.FromUnformatted(status));

        switch (state.Mode)
        {
            case BitrunUiMode.Console:
                UpdateConsole(state, previous, selectedDomain);
                break;
            case BitrunUiMode.Pod:
                UpdatePod(state, previous, selectedSession);
                break;
            case BitrunUiMode.Vendor:
                if (previous is null || !previous.ShopItems.SequenceEqual(state.ShopItems))
                    RebuildShop(state, selectedItem);
                UpdateShop();
                break;
        }

        UpdateSessionDetails();
    }

    public void SetBalances(int credits, int researchPoints)
    {
        _personalCredits = credits;
        _personalResearchPoints = researchPoints;
        UpdateShop();
    }

    private void UpdateConsole(BitrunUiState state, BitrunUiState? previous, string? selectedDomain)
    {
        RunStats.Text = Loc.GetString("bitrun-ui-run-stats", ("credits", state.Credits));

        if (previous is null || !previous.ResearchServers.SequenceEqual(state.ResearchServers))
        {
            ResearchChoice.Clear();
            ResearchChoice.AddItem(Loc.GetString("bitrun-ui-unlinked"));
            ResearchChoice.SetItemDisabled(0, true);
            foreach (var server in state.ResearchServers)
                ResearchChoice.AddItem(server.Name);
        }

        var selectedServer = Array.FindIndex(state.ResearchServers, server => server.Entity == state.ResearchServer);
        ResearchChoice.SelectId(selectedServer + 1);
        ResearchChoice.Disabled = state.ResearchServers.Length == 0;

        if (previous is null || !previous.Domains.SequenceEqual(state.Domains))
        {
            DomainChoice.Clear();
            if (state.Domains.Length == 0)
                DomainChoice.AddItem(Loc.GetString("bitrun-ui-no-domains"));
            foreach (var domain in state.Domains)
                DomainChoice.AddItem(domain.Name);
        }

        var selectedIndex = Array.FindIndex(state.Domains, domain => domain.Id == (state.DomainId ?? selectedDomain));
        if (state.Domains.Length > 0)
            DomainChoice.SelectId(Math.Max(selectedIndex, 0));

        DomainChoice.Disabled = state.Domains.Length == 0 || state.Sessions.Length > 0;
        RandomButton.Disabled = !state.CanStart;
        var session = SelectedSession();
        var previousSession = previous?.Sessions.FirstOrDefault();
        if (previous == null || previous.CanStop != state.CanStop ||
            previousSession?.Id != session?.Id || previousSession?.Waiting != session?.Waiting)
        {
            var waiting = session is { Waiting: true };
            StopButton.IsConfirming = false;
            StopButton.Disabled = !state.CanStop;
            StopButton.Text = Loc.GetString(waiting ? "bitrun-ui-cancel-lobby" : "bitrun-ui-stop");
            StopButton.ConfirmationText = Loc.GetString(waiting ? "bitrun-ui-confirm-cancel-lobby" : "bitrun-ui-confirm-stop");
        }
        UpdateDomainDetails();
    }

    private void UpdatePod(BitrunUiState state, BitrunUiState? previous, Guid? selectedSession)
    {
        if (previous is null || !previous.Loadouts.SequenceEqual(state.Loadouts))
        {
            LoadoutChoice.Clear();
            if (state.Loadouts.Length == 0)
                LoadoutChoice.AddItem(Loc.GetString("bitrun-ui-no-loadouts"));
            foreach (var loadout in state.Loadouts)
                LoadoutChoice.AddItem(Loc.GetString($"bitrun-loadout-{loadout}"));
        }

        var index = Array.IndexOf(state.Loadouts, state.SelectedLoadout);
        if (state.Loadouts.Length > 0)
            LoadoutChoice.SelectId(Math.Max(index, 0));

        if (previous is null || !previous.Sessions.Select(entry => (entry.Id, entry.Waiting, entry.Domain))
            .SequenceEqual(state.Sessions.Select(entry => (entry.Id, entry.Waiting, entry.Domain))))
        {
            SessionChoice.Clear();
            if (state.Sessions.Length == 0)
                SessionChoice.AddItem(Loc.GetString("bitrun-ui-no-sessions"));
            for (var i = 0; i < state.Sessions.Length; i++)
            {
                var entry = state.Sessions[i];
                SessionChoice.AddItem(Loc.GetString(entry.Waiting ? "bitrun-ui-session-waiting" : "bitrun-ui-session-active",
                    ("domain", entry.Domain), ("server", entry.Server.ToString())));
            }

            var selected = Array.FindIndex(state.Sessions, entry => entry.Id == selectedSession);
            if (selected < 0)
                SideChoice.SelectId(0);
            SessionChoice.SelectId(Math.Max(selected, 0));
        }

        SessionChoice.Disabled = state.Sessions.Length == 0 || state.CanStop && !_preparing;
        LoadoutChoice.Disabled = state.Loadouts.Length == 0 || state.CanStop && !_preparing;
        EjectButton.Disabled = !state.CanStop;
        EjectButton.Text = Loc.GetString(state.CanStop && !_preparing && SelectedSession() is { Waiting: true }
            ? "bitrun-ui-cancel-entry"
            : "bitrun-ui-eject");
    }

    private BitrunSessionEntry? SelectedSession()
    {
        var index = _state?.Mode == BitrunUiMode.Console ? 0 : SessionChoice.SelectedId;
        return _state is { } state && index >= 0 && index < state.Sessions.Length ? state.Sessions[index] : null;
    }

    private BitrunSide? SelectedSide() => SideChoice.SelectedId switch
    {
        1 => BitrunSide.Attackers,
        2 => BitrunSide.Defenders,
        _ => null,
    };

    private void UpdateSessionDetails()
    {
        var session = SelectedSession();
        SessionStats.Visible = session != null;
        SessionTimer.Visible = session != null;
        if (session != null)
        {
            SessionStats.Text = Loc.GetString("bitrun-ui-team-counts",
                ("attackers", session.Attackers), ("defenders", session.Defenders));
        }

        _shownSeconds = null;
        UpdateCountdown();
        if (_state is not { Mode: BitrunUiMode.Pod } state)
            return;

        var canJoinAttackers = session is { CanJoinAttackers: true };
        var canJoinDefenders = session is { CanJoinDefenders: true };
        SideChoice.SetItemDisabled(1, !canJoinAttackers);
        SideChoice.SetItemDisabled(2, !canJoinDefenders);
        SideChoice.Disabled = !state.CanStart || state.CanStop && !_preparing || !canJoinAttackers && !canJoinDefenders;

        var selectedSide = SelectedSide();
        var enabled = selectedSide == BitrunSide.Attackers && canJoinAttackers ||
                      selectedSide == BitrunSide.Defenders && canJoinDefenders;
        if (state.OccupiedSide is { } occupiedSide)
            SideChoice.SelectId(occupiedSide == BitrunSide.Attackers ? 1 : 2);
        else if (!enabled)
            SideChoice.SelectId(0);

        EnterButton.Disabled = !state.CanStart || state.CanStop && !_preparing || !enabled;
        EnterButton.Text = Loc.GetString(session is { Waiting: true } ? "bitrun-ui-enqueue" : "bitrun-ui-enter");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
    }

    private void UpdateCountdown()
    {
        if (SelectedSession() is not { } session)
            return;

        var seconds = Math.Max(0, (int) Math.Ceiling((session.Deadline - _timing.CurTime).TotalSeconds));
        if (_shownSeconds == seconds)
            return;

        _shownSeconds = seconds;
        var time = $"{seconds / 60}:{seconds % 60:00}";
        SessionTimer.Text = Loc.GetString(session.Waiting ? "bitrun-ui-starts-in" : "bitrun-ui-ends-in", ("time", time));
    }

    private BitrunDomainEntry? SelectedDomain()
    {
        var index = DomainChoice.SelectedId;
        return _state is { } state && index >= 0 && index < state.Domains.Length ? state.Domains[index] : null;
    }

    private void UpdateDomainDetails()
    {
        var selected = SelectedDomain();
        StartButton.Disabled = selected is not { } domainEntry || _state is not { CanStart: true } state || domainEntry.Cost > state.Credits;
        if (selected is not { } domain)
        {
            DomainDetails.SetMessage(FormattedMessage.FromUnformatted(Loc.GetString("bitrun-ui-no-domains")));
            return;
        }

        var difficulty = Loc.GetString($"bitrun-ui-difficulty-{domain.Difficulty}");
        var costs = Loc.GetString("bitrun-ui-domain-stats",
            ("difficulty", difficulty), ("cost", domain.Cost), ("reward", domain.Reward));
        DomainDetails.SetMessage(FormattedMessage.FromUnformatted(costs + "\n" + domain.Description));
    }

    private void RebuildShop(BitrunUiState state, string? selectedItem)
    {
        ShopChoice.Clear();
        if (state.ShopItems.Length == 0)
            ShopChoice.AddItem(Loc.GetString("bitrun-ui-no-shop-items"));
        foreach (var item in state.ShopItems)
            ShopChoice.AddItem(Loc.GetString("bitrun-ui-shop-entry", ("item", item.Name), ("price", item.Price)));

        var index = Array.FindIndex(state.ShopItems, item => item.Id == selectedItem);
        if (state.ShopItems.Length > 0)
            ShopChoice.SelectId(Math.Max(index, 0));
    }

    private BitrunShopEntry? SelectedShopItem()
    {
        var index = ShopChoice.SelectedId;
        return _state is { } state && index >= 0 && index < state.ShopItems.Length ? state.ShopItems[index] : null;
    }

    private void UpdateShop()
    {
        var credits = _personalCredits ?? 0;
        PersonalBalance.Text = Loc.GetString("bitrun-ui-personal-balance", ("credits", credits));
        PersonalResearchPoints.Text = Loc.GetString("bitrun-ui-personal-research-points", ("points", _personalResearchPoints ?? 0));
        ShopChoice.Disabled = _state is not { ShopItems.Length: > 0 };
        BuyButton.Disabled = SelectedShopItem() is not { } item || item.Price > credits;
    }

    private void Request(BitrunUiAction action, string? id = null, NetEntity? target = null, BitrunSide? side = null,
        Guid? session = null)
    {
        ActionRequested?.Invoke(new BitrunUiMessage(action, id, target, side, session));
    }
}
