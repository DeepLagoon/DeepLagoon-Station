using System.Linq;
using Robust.Client.UserInterface.Controls;
using Content.Client.Message;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using static Robust.Client.UserInterface.StylesheetHelpers;
using Content.Client.Voting.UI;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;

        private string _lastLobbyState = "";

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            Chat.ChatInput.UseCompactLayout();
            Chat.EnableTguiChat();
            // Keep the original buttons and their controller bindings, including the
            // character setup button's preferences-loaded state.
            var setup = CharacterPreview.CharacterSetupButton;
            setup.Orphan();
            setup.Margin = new Thickness(0);
            setup.HorizontalAlignment = HAlignment.Stretch;
            CharacterPreview.FindControl<Control>("Header").HorizontalAlignment = HAlignment.Center;
            VoteContainer.OnChildAdded += popup =>
            {
                popup.MinWidth = 0;
                if (popup is VotePopup vote)
                    vote.ApplyLobbyStyle();
            };
            CharacterSetupSlot.AddChild(setup);
            LobbyButtonArtwork.AttachReady(ReadyButton);
            LobbyButtonArtwork.Attach(ObserveButton, "observe", () => "observe");
            LobbyButtonArtwork.Attach(setup, "character_setup", () => "character_setup");
            foreach (var button in new[] { AHelpButton, CallVoteButton, OptionsButton, LeaveButton })
                LobbyButtonArtwork.AttachUtility(button);

            // Keep all original callbacks and configured link visibility while restyling.
            DecorateBanner(LinkBanner);
            DecorateBanner(DevInfoBanner);
            DevInfoBanner.Visible = false;
            ServerInfo.TextColor = LobbyConsoleTheme.Green;
            ServerInfo.Stylesheet = new Stylesheet(new StyleRule[]
            {
                Element<RichTextLabel>().Prop("font", LobbyConsoleTheme.GetFont())
                    .Prop(nameof(RichTextLabel.LineHeightScale), 1.7f).Prop("font-outline-thickness", 0f),
            });
            HeaderContainer.Visible = LobbyInfoScroll.Visible = StartTime.Visible = false;

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();
        }

        private void DecorateBanner(Control banner)
        {
            foreach (var row in banner.Children.ToArray())
            foreach (var link in row.Children.ToArray())
            {
                link.Orphan();
                if (link is Button button)
                    LobbyButtonArtwork.AttachUtility(button);
                UtilityButtons.AddChild(link);
            }
            banner.DisposeAllChildren();
            // LinkBanner stays in the tree: it still updates its configured link
            // visibility on EnteredTree, even though its buttons share our grid.
        }

        protected override void FrameUpdate(Robust.Shared.Timing.FrameEventArgs args)
        {
            base.FrameUpdate(args);
            HeaderContainer.Visible = LobbyInfoScroll.Visible = StartTime.Visible = Chat.WebChat == null;
            var state = new Content.Client._DeepLagoon.WebUI.TguiData().String("server", ServerName.Text)
                .String("time", StationTime.Text).String("status", StartTime.Text).ToString();
            if (Chat.WebChat?.IsReady == true && state != _lastLobbyState)
            {
                _lastLobbyState = state;
                Chat.WebChat.Send("deeplagoon/lobby-status", state);
            }
            if (Chat.WebChat?.IsReady != true) _lastLobbyState = "";
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = !EntryDrawer.Collapsed;
                    RightSide.Visible = true;
                    break;
                case LobbyGuiState.CharacterSetup:
                      DefaultState.Visible = !EntryDrawer.Collapsed;
                      RightSide.Visible = true;
                      UserInterfaceManager.GetUIController<LobbyUIController>().OpenCharacterEditor();

                    break;
            }
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
