using System.Numerics;
using System.Linq;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using static Robust.Client.UserInterface.StylesheetHelpers;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    public const float PreviewSize = 224;
    [Dependency] private IEntityManager _entManager = default!;

    public Button CharacterSetupButton => CharacterSetup;

    private EntityUid? _previewDummy;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SetWidth = LobbyButtonPanel.BackplateWidth;
        HorizontalAlignment = HAlignment.Center;
        Frame.PanelOverride = LobbyConsolePanel.CreateFrame((LobbyButtonPanel.BackplateWidth - PreviewSize) / 2);
        Stylesheet = new Stylesheet(new StyleRule[]
        {
            Element<Label>().Prop("font", LobbyConsoleTheme.GetFont())
                .Prop("font-color", LobbyConsoleTheme.Green).Prop("font-outline-thickness", 0f),
            Element<RichTextLabel>().Prop("font", LobbyConsoleTheme.GetFont()).Prop("font-outline-thickness", 0f),
        });
        Header.FontOverride = LobbyConsoleTheme.GetFont(15);
        CharacterSetup.Disabled = true;
    }

    public void SetLoaded(bool value)
    {
        CharacterSetup.Disabled = !value;
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        Summary.Text = value;
        Summary.ToolTip = value;
    }

    // Frontier: show bank balance on character selection.
    public void SetBankBalance(long? value)
    {
        BankBalance.Value = value;
    }
    // End Frontier

    // Company Display
    public void SetCompanyText(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            Company.SetMessage(string.Empty);
            return;
        }

        Company.SetMessage(FormattedMessage.FromMarkupPermissive(value), defaultColor: LobbyConsoleTheme.Green);
    }
    // End Company Display

    public void SetLagoonCoinBalance(long value) => LagoonCoins.Value = value < 0 ? null : value;

    public void SetSprite(EntityUid uid)
    {
        if (_previewDummy != null)
        {
            _entManager.DeleteEntity(_previewDummy);
        }

        _previewDummy = uid;

        foreach (var oldView in ViewBox.Children.OfType<SpriteView>().ToArray())
            oldView.Orphan();
        var spriteView = new SpriteView
        {
            OverrideDirection = Direction.South,
            Scale = new Vector2(4f, 4f),
            // Fill normalizes species/body bounds inside a permanently large
            // viewport. Neither metadata length nor window resizing can shrink it.
            SetSize = new Vector2(PreviewSize),
            MinSize = new Vector2(PreviewSize),
            MaxSize = new Vector2(PreviewSize),
            Stretch = SpriteView.StretchMode.Fill,
        };
        spriteView.SetEntity(uid);
        ViewBox.AddChild(spriteView);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        _entManager.DeleteEntity(_previewDummy);
        _previewDummy = null;
    }
}
