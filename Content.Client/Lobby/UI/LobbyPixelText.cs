    public static void Draw(DrawingHandleScreen handle, string text, Vector2 origin, float pixel, Color color)
    {
        foreach (var letter in text.ToUpperInvariant())
        {
            var glyph = Glyphs.GetValueOrDefault(letter, Glyphs['?']);
            for (var y = 0; y < 7; y++)
            for (var x = 0; x < 5; x++)
            {
                if ((glyph[y] & (1 << (4 - x))) != 0)
                    handle.DrawRect(UIBox2.FromDimensions(origin + new Vector2(x, y) * pixel, new Vector2(pixel)), color);
            }
            origin.X += 6 * pixel;
        }
    }
