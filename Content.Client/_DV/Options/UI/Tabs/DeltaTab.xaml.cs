using Content.Client._DeepLagoon.AmbientOcclusion;
using Content.Client.Options.UI;
using Content.Shared._DV.CCVars;
using Content.Shared._DeepLagoon.BodyCustomization;
using Content.Shared._DeepLagoon.Tattoos;
using Content.Shared._DeepLagoon.WebUI;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared;
using Robust.Shared.Configuration;

namespace Content.Client._DV.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class DeltaTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;

    public DeltaTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var interfaceStyle = Control.AddOptionDropDown(WebUiCVars.InterfaceStyle, DropDownInterfaceStyle,
            new OptionDropDownCVar<int>.ValueOption[]
            {
                new(0, Loc.GetString("dl-ui-style-unselected")),
                new(1, Loc.GetString("dl-ui-style-tgui")),
                new(2, Loc.GetString("dl-ui-style-classic")),
            });
        interfaceStyle.ImmediateValueChanged += style => VanillaChat.Pressed = !WebUiCVars.UseTgui(style);
        Control.AddOptionCheckBox(WebUiCVars.VanillaChat, VanillaChat);
        Control.AddOptionCheckBox(CCVars.LobbyAnimatedBackground, LobbyAnimatedBackgroundCheckBox);
        Control.AddOptionCheckBox(TattooCVars.Enabled, TattoosEnabled);
        Control.AddOptionCheckBox(BodyCustomizationCVars.ChemicalChanges, BodyChemicalChangesCheckBox);
        Control.AddOptionCheckBox(DCCVars.NoVisionFilters, DisableFiltersCheckBox);

        Control.AddOption(new PredictionOption(this, _cfg));
        Control.AddOptionSlider(CVars.NetPredictTickBias, PredictionTicksSlider, 0, 8);
        AddMillisecondsSlider(CVars.NetPredictLagBias, PredictionLagSlider, 100);
        AddMillisecondsSlider(CVars.NetInterpCorrectionHalfLife, PredictionSmoothingSlider, 300);

        Control.AddOptionCheckBox(CCVars.LightBloomEnabled, LightBloomCheckBox);
        Control.AddOptionSlider(CCVars.LightBloomIntensity, LightBloomIntensitySlider,
            0, 100, (_, value) => $"{value}%");
        Control.AddOptionCheckBox(CCVars.AmbientOcclusionEnabled, ContactOcclusionCheckBox);
        Control.AddOptionCheckBox(CCVars.AmbientOcclusionEntities, AmbientOcclusionEntitiesCheckBox);
        Control.AddOptionSlider(CCVars.AmbientOcclusionIntensity, AmbientOcclusionIntensitySlider,
            100, 300, (_, value) => $"{value}%");
        Control.AddOptionSlider(CCVars.AmbientOcclusionDrawDistance, AmbientOcclusionDrawDistanceSlider,
            AmbientOcclusionRange.MinDistance, AmbientOcclusionRange.MaxDistance,
            (_, value) => Loc.GetString("ui-options-ambient-occlusion-draw-distance-value", ("distance", value)));
        Control.AddOptionSlider(CCVars.AmbientOcclusionMaxCasters, AmbientOcclusionMaxCastersSlider,
            AmbientOcclusionRange.MinCasters, AmbientOcclusionRange.MaxCasters);

        Control.Initialize();
        UpdatePredictionControls(ClientPredictionCheckBox.Pressed);
    }

    // Keep dependent controls in sync for loading, discarding and resetting as well as user clicks.
    private sealed class PredictionOption : BaseOptionCVar<bool>
    {
        private readonly DeltaTab _tab;

        protected override bool Value
        {
            get => _tab.ClientPredictionCheckBox.Pressed;
            set
            {
                _tab.ClientPredictionCheckBox.Pressed = value;
                _tab.UpdatePredictionControls(value);
            }
        }

        public PredictionOption(DeltaTab tab, IConfigurationManager cfg) : base(tab.Control, cfg, CVars.NetPredict)
        {
            _tab = tab;
            tab.ClientPredictionCheckBox.OnToggled += _ =>
            {
                tab.UpdatePredictionControls(Value);
                ValueChanged();
            };
        }
    }

    private void AddMillisecondsSlider(CVarDef<float> cvar, OptionSlider slider, int max)
    {
        // The UI uses milliseconds; the engine stores these values in seconds.
        slider.Slider.Rounded = true;
        Control.AddOption(new OptionSliderFloatCVar(Control, _cfg, cvar, slider, 0, max, 0.001f,
            (_, value) => Loc.GetString("dl-options-milliseconds", ("value", (int) MathF.Round(value)))));
    }

    private void UpdatePredictionControls(bool enabled)
    {
        PredictionTicksSlider.Slider.Disabled = !enabled;
        PredictionLagSlider.Slider.Disabled = !enabled;
        PredictionSmoothingSlider.Slider.Disabled = !enabled;
    }
}
