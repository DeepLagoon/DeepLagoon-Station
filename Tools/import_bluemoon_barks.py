"""Import the effective BlueMoon bark catalog from a local checkout.

Usage: py -3 Tools/import_bluemoon_barks.py C:/path/to/MOLOT-BlueMoon-Station
Requires FFmpeg and ffprobe. Mono assets are copied unchanged.
"""

from decimal import Decimal
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "Resources/Audio/_DeepLagoon/Speech/BlueMoon"
CATALOG = ROOT / "Resources/Prototypes/_DeepLagoon/Speech/bluemoon_barks.yml"
UPSTREAM = "https://github.com/iamasay/MOLOT-BlueMoon-Station"
DATUM = "/datum/bark"
FIELDS = {
    "minspeed": ("minSpeed", "BARK_DEFAULT_MINSPEED"),
    "maxspeed": ("maxSpeed", "BARK_DEFAULT_MAXSPEED"),
    "minpitch": ("minPitch", "BARK_DEFAULT_MINPITCH"),
    "maxpitch": ("maxPitch", "BARK_DEFAULT_MAXPITCH"),
    "minvariance": ("minVariance", "BARK_DEFAULT_MINVARY"),
    "maxvariance": ("maxVariance", "BARK_DEFAULT_MAXVARY"),
}
KNOWN_FIELDS = set(FIELDS) | {"name", "id", "soundpath", "ignore", "allow_random"}


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def read_catalog(root):
    defines = (root / "code/__DEFINES/say.dm").read_text(encoding="utf-8-sig")
    numbers = dict(re.findall(r"^#define\s+(BARK_DEFAULT_\w+)\s+([.\d]+)", defines, re.M))
    declarations = {DATUM: {key: define for key, (_, define) in FIELDS.items()}}
    project = (root / "tgstation.dme").read_text(encoding="utf-8-sig")
    for include in re.findall(r'^#include "([^"]+)"', project, re.M):
        name = include.replace("\\", "/")
        if Path(name).name not in {"bark.dm", "centipede_voice.dm"}:
            continue
        current = None
        for line in (root / name).read_text(encoding="utf-8-sig").splitlines():
            if line.startswith("/"):
                path = line.split("//", 1)[0].strip()
                current = path if path.startswith(DATUM + "/") and "/proc/" not in path else None
                if current:
                    declarations.setdefault(current, {})
                continue
            if not current:
                continue
            match = re.match(r"^\t(\w+)\s*=\s*(\"[^\"]*\"|'[^']*'|[^/]+)", line)
            if match:
                key, value = match.groups()
                if key not in KNOWN_FIELDS:
                    raise ValueError(f"{name}: unsupported bark setting {key}")
                declarations[current][key] = value.strip()

    def number(expression):
        factors = [Decimal(numbers.get(part, part)) for part in expression.replace(" ", "").split("*")]
        result = Decimal(1)
        for factor in factors:
            result *= factor
        return format(result.normalize(), "f")

    catalog = {}
    folded_ids = set()
    for path in declarations:
        if path == DATUM:
            continue
        parts = path.split("/")
        merged = {}
        for end in range(3, len(parts) + 1):
            merged.update(declarations.get("/".join(parts[:end]), {}))
        voice = merged["id"].strip('"')
        if not re.fullmatch(r"[A-Za-z0-9_]+", voice) or voice.lower() in folded_ids:
            raise ValueError(f"Unsupported or duplicate bark ID: {voice}")
        folded_ids.add(voice.lower())
        sound = merged["soundpath"].strip("'")
        if not (root / sound).is_file():
            raise FileNotFoundError(sound)
        params = {field: number(merged[key]) for key, (field, _) in FIELDS.items()}
        catalog[voice] = (merged["name"].strip('"'), sound, params,
                          merged.get("ignore") == "TRUE", merged.get("allow_random") == "TRUE")
    if len(catalog) < 100:
        raise ValueError(f"Incomplete BlueMoon catalog: {len(catalog)} voices")
    return catalog


def import_sound(source, target):
    probe = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "stream=codec_name,channels",
         "-of", "json", str(source)], capture_output=True, check=True,
    )
    stream, = json.loads(probe.stdout)["streams"]
    if stream == {"codec_name": "vorbis", "channels": 1}:
        shutil.copyfile(source, target)
        return "Copied without changes."
    subprocess.run(
        ["ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-xerror", "-y",
         "-i", str(source), "-ac", "1", "-c:a", "libvorbis", "-q:a", "6", str(target)],
        check=True,
    )
    return "Converted to mono Ogg Vorbis for positional audio."


def main():
    source = Path(sys.argv[1]).resolve(strict=True)
    voices = read_catalog(source)
    revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    AUDIO.mkdir(parents=True, exist_ok=True)
    CATALOG.parent.mkdir(parents=True, exist_ok=True)
    prototypes = [f"# Generated by Tools/import_bluemoon_barks.py from MOLOT-BlueMoon-Station {revision}.\n"]
    credits = [
        "# Asset provenance. BlueMoon's repository-wide notice gives CC BY-SA 3.0 as the default.",
        "# Individual rights for third-party samples are not established by this import.",
        f"# {UPSTREAM}/blob/{revision}/README.md",
    ]
    for voice, (name, path, settings, hidden, random) in voices.items():
        asset = f"{voice}.ogg"
        operation = import_sound(source / path, AUDIO / asset)
        prototypes.extend([
            "- type: speechBarkVoice", f"  id: {voice}", f"  name: {quote(name)}",
            f"  sound: /Audio/_DeepLagoon/Speech/BlueMoon/{asset}",
            *(f"  {field}: {value}" for field, value in settings.items()),
        ])
        if hidden:
            prototypes.append("  hidden: true")
        if random:
            prototypes.append("  allowRandom: true")
        prototypes.append("")
        credits.extend([
            f"- files: [{quote(asset)}]", "  license: Custom",
            f"  source: {quote(f'{UPSTREAM}/blob/{revision}/{path}')}",
            f"  copyright: {quote(f'{name}. Source: {path}. {operation} See source repository and original rights holders.')}",
        ])
    CATALOG.write_text("\n".join(prototypes), encoding="utf-8", newline="\n")
    (AUDIO / "attributions.yml").write_text("\n".join(credits) + "\n", encoding="utf-8", newline="\n")
    print(f"Imported {len(voices)} voices, {sum(voice[3] for voice in voices.values())} hidden")


if __name__ == "__main__":
    main()
