"""Generate entity Fluent entries without exposing importer identifiers to players.

Authored translations take precedence over exact matches in the station's
existing English/Russian entity catalogs. Source text remains the fallback;
untranslated text is reported instead of being disguised as translated text.
"""
from pathlib import Path
import json
import re


def authored(path):
    return dict(line.split('\t', 1) for line in path.read_text(encoding='utf-8').splitlines()
                if line and not line.startswith('#'))


def catalog(root):
    result = {}
    for path in sorted(root.rglob('*.ftl')):
        if path.name == 'source-entities.generated.ftl':
            continue
        text = path.read_text(encoding='utf-8-sig')
        result.update(re.findall(r'^(ent-[\w-]+)\s*=\s*([^\n]*)', text, re.M))
    return result


def plain(text):
    return re.sub(r'<[^>]+>', '', text.replace('<br>', '\n').replace('<br/>', '\n')).strip()


def write_locales(station, rows, verify):
    translations = authored(Path(__file__).with_name('translations_ru.tsv'))
    descriptions = {plain(key): value for key, value in authored(Path(__file__).with_name('descriptions_ru.tsv')).items()}
    descriptions.update(json.loads(Path(__file__).with_name('descriptions_ru.json').read_text(encoding='utf-8')))
    english = catalog(station / 'Resources/Locale/en-US')
    russian = catalog(station / 'Resources/Locale/ru-RU')
    native = {name: '{ ' + key + ' }' for key, name in english.items() if name and key in russian}
    result = {'en-US': [], 'ru-RU': []}
    missing = set()
    missing_descriptions = set()
    for prototype, row in sorted(rows.items()):
        if 'name' not in row:
            continue
        name = row['name']
        ru = translations.get(name) or native.get(name)
        if ru is None:
            # Calibers and model names are retained; grammatical ammunition
            # suffixes are translated independently of their caliber spelling.
            for source, target in [(' armor-piercing bullet casing', ' — бронебойный патрон'),
                                   (' surplus bullet casing', ' — патрон из армейских запасов'),
                                   (' lethal bullet casing', ' — боевой патрон'),
                                   (' bullet casing', ' — патрон'), (' casing', ' — патрон'),
                                   (' caseless cartridge', ' — безгильзовый патрон'),
                                   (' armor-piercing bullet', ' — бронебойная пуля'),
                                   (' surplus bullet', ' — пуля из армейских запасов'),
                                   (' bullet', ' — пуля')]:
                if name.endswith(source):
                    ru = name.removesuffix(source) + target
                    break
        if ru is None:
            ru = name
            missing.add(name)
        for language, title in [('en-US', name), ('ru-RU', ru)]:
            result[language].append(f'ent-{prototype} = {title}')
            if description := plain(row.get('description', '')):
                if language == 'ru-RU':
                    if translated := descriptions.get(description):
                        description = translated
                    elif re.fullmatch(r'A [\w.×x\- ]+ (?:bullet )?casing\.', description):
                        description = 'Патрон ' + description[2:].removesuffix(' bullet casing.').removesuffix(' casing.') + '.'
                    else:
                        missing_descriptions.add(prototype)
                result[language].append('    .desc = ' + description.replace('\n', '\n        '))
            result[language].append('')
    for language, lines in result.items():
        path = station / f'Resources/Locale/{language}/_DeepLagoon/bitrunning/source-entities.generated.ftl'
        encoded = '# Generated by Tools/bitrunning/import_maps.py.\n' + '\n'.join(lines)
        encoded = '\n'.join(line.rstrip() for line in encoded.split('\n'))
        if verify:
            if not path.exists() or path.read_text(encoding='utf-8') != encoded:
                raise ValueError(f'Out of date localization: {path}')
        else:
            path.write_text(encoded, encoding='utf-8', newline='\n')
    return {'names': sorted(missing), 'descriptions': sorted(missing_descriptions)}
