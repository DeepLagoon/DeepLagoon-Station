"""Import original LustWish names, descriptions and SS13 slot declarations.

Usage: python Tools/lustwish/import_items.py <WhiteMoon checkout> [--check]
The source type mapping is intentionally explicit; unrelated Station entities are untouched.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIELDS = {'name', 'desc', 'slot_flags', 'parent_type'}

def declarations(source):
    types = {}
    includes = re.findall(r'^#include "([^"]+\.dm)"', (source / 'tgstation.dme').read_text(encoding='utf-8-sig'), re.M)
    for name in includes:
        path = source / name.replace('\\', '/')
        if not path.exists(): continue
        current = None
        lines = iter(path.read_text(encoding='utf-8-sig', errors='replace').splitlines())
        for line in lines:
            if line.startswith('/'):
                match = re.match(r'^(/[\w/]+)\s*(?://.*)?$', line)
                current = match[1] if match else None
                continue
            if current is None: continue
            match = re.match(r'^\t(name|desc|slot_flags|parent_type)\s*=\s*(.*)$', line)
            if not match: continue
            value = match[2]
            while value.endswith('\\'):
                value = value[:-1] + next(lines).lstrip()
            if value.startswith('{"'):
                while not re.search(r'"}\s*(?://.*)?$', value): value += '\n' + next(lines)
                value = value[1:value.rfind('}')]
            # Comments are only comments outside quoted strings.
            quote = False; escape = False; stop = len(value)
            for i, c in enumerate(value):
                if escape: escape = False; continue
                if c == '\\': escape = True; continue
                if c == '"': quote = not quote
                if not quote and value[i:i+2] == '//': stop = i; break
            types.setdefault(current, {})[match[1]] = value[:stop].strip()
    return types

def inherited(types, name, seen=()):
    if not name: return {}
    if name in seen: raise ValueError('Cyclic parent_type: '+name)
    own = types.get(name, {})
    parent = own.get('parent_type', name.rsplit('/', 1)[0])
    return inherited(types, parent, (*seen,name)) | own

def string(value):
    if value in (None, 'null'): return ''
    if not value.startswith('"') or not value.endswith('"'): raise ValueError('Non-literal metadata: '+value)
    value = value[1:-1].replace('\\improper ', '').replace('\\proper ', '')
    return re.sub(r'\\([ntr"\\\[\]])', lambda m: {'n':'\n','t':'\t','r':'\r'}.get(m[1],m[1]), value)

def ftl(value):
    if not value.strip(): return '{ ' + json.dumps(value) + ' }'
    # Fluent braces are syntax, while source braces are literal text.
    value = value.replace('{','\x01').replace('}','\x02').replace('\x01','{"{"}').replace('\x02','{"}"}')
    return '\n        '.join(value.splitlines()) if value else '{ "" }'

def render_locale(records, language):
    descriptions = {key:data['description'] for key,data in records.items()}
    header = '# Original WhiteMoon metadata; generated by Tools/lustwish/import_items.py.\n'
    if language == 'ru-RU':
        descriptions = json.loads(Path(__file__).with_name('descriptions.ru.json').read_text(encoding='utf-8'))
        if descriptions.keys() != records.keys(): raise ValueError('Russian description keys must match imported prototypes')
        header = '# Original WhiteMoon names and Russian descriptions; generated by Tools/lustwish/import_items.py.\n'
    return header + ''.join(f"ent-{key} = {ftl(data['name'])}\n    .desc = {ftl(descriptions[key])}\n" for key,data in records.items())

def run(source, check=False):
    manifest = json.loads(Path(__file__).with_name('items.json').read_text())
    revision = subprocess.check_output(['git','-c',f'safe.directory={source.as_posix()}','-C',str(source),'rev-parse','HEAD'],text=True).strip()
    if revision != manifest['revision']: raise ValueError('Unexpected source revision: '+revision)
    types = declarations(source)
    records = {id:{'sourceType':t,'name':string(p.get('name')),'description':string(p.get('desc')),'sourceSlots':p.get('slot_flags','0')}
               for id,t in manifest['items'].items() for p in [inherited(types,t)]}
    changes = []
    for file in (ROOT/'Resources/Prototypes/_DeepLagoon/LustWish').glob('*.yml'):
        text = file.read_text(encoding='utf-8-sig')
        chunks = re.split(r'(?=^- type: )', text, flags=re.M)
        for i, chunk in enumerate(chunks):
            match = re.search(r'^  id: (.+)$',chunk,re.M)
            if not match or match[1] not in records: continue
            data = records[match[1]]
            chunk = re.sub(r'^  (?:name|description):[^\n]*(?:\n {4,}[^\n]*)*\n?', '', chunk, flags=re.M)
            pos = re.search(r'^  id: .+\n', chunk, re.M).end()
            chunk = chunk[:pos] + '  name: '+json.dumps(data['name'],ensure_ascii=False)+'\n  description: '+json.dumps(data['description'],ensure_ascii=False)+'\n'+chunk[pos:]
            chunks[i]=chunk
        changes.append((file,''.join(chunks)))
    for language in ('en-US','ru-RU'):
        folder = ROOT/f'Resources/Locale/{language}/_DeepLagoon'
        # Remove old metadata overrides, retaining UI and reagent translations.
        for file in folder.glob('lustwish*.ftl'):
            text=file.read_text(encoding='utf-8-sig')
            text=re.sub(r'^ent-([\w]+)\s*=[^\n]*(?:\n[ \t]+[^\n]*)*\n?', lambda m: '' if m[1] in records else m[0], text,flags=re.M)
            changes.append((file,text if text.strip() else ''))
        changes=[(p,t) for p,t in changes if p != folder/'lustwish-source.ftl']
        changes.append((folder/'lustwish-source.ftl',render_locale(records, language)))
    changes.append((Path(__file__).with_name('source_metadata.json'),json.dumps({'revision':revision,'items':records},ensure_ascii=False,indent=2)+'\n'))
    failed=[]
    for file,text in changes:
        old=file.read_text(encoding='utf-8-sig') if file.exists() else ''
        if old != text:
            if check: failed.append(str(file.relative_to(ROOT)))
            else: file.write_text(text,encoding='utf-8')
    if failed: raise SystemExit('Metadata differs: '+', '.join(failed))
    print(f'{len(records)} original item names/descriptions verified' if check else f'{len(records)} original item names/descriptions imported')

if __name__ == '__main__': run(Path(sys.argv[1]).resolve(), '--check' in sys.argv)
